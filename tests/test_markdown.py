class TestEscaping(unittest.TestCase):
    def lead(self, *paragraphs: str) -> str:
        page = body(file_doc("a.py", Section("purpose", "Purpose", text=paragraphs)))
        return page.removeprefix("# a.py\n\n")

    def test_line_starts_that_would_become_structure_are_escaped(self) -> None:
        text = "\n\n".join([
            "# not a heading", "> not a quote", "- not a list", "+ not a list",
            "* not a list", "1. not a list", "2) not a list", "~~~ not a fence",
            "``` not a fence", "--- not a rule", "-1 stays", "12.5 stays",
        ])
        self.assertEqual(self.lead(text), md(r"""
\# not a heading

\> not a quote

\- not a list

\+ not a list

\* not a list

1\. not a list

2\) not a list

\~\~\~ not a fence

\`\`\` not a fence

\--- not a rule

-1 stays

12.5 stays
"""))

    def test_list_items_escape_their_start_too(self) -> None:
        document = file_doc("a.py", Section("behaviour", "Behaviour", items=(
            Item("# heading"), Item("1. numbered"), Item("> quoted"),
            Item("[ ] not a task"), Item("[x] not done"), Item("[X]"),
            Item("[y] stays"), Item("[x](stays) too"),
        )))
        self.assertEqual(body(document), md(r"""
# a.py

## Behaviour

- \# heading
- 1\. numbered
- \> quoted
- \[ ] not a task
- \[x] not done
- \[X]
- [y] stays
- [x\](stays) too
"""))

    def test_code_spans_are_never_touched(self) -> None:
        text = "Use `a_b * c ~d~ | <d> [e](f) \\` here, and ``x ` y`` too."
        self.assertEqual(self.lead(text), text + "\n")

    def test_escaping_judges_text_as_it_lands_on_the_line(self) -> None:
        """Surrounding whitespace is stripped before escaping, so a marker that
        spaces made inert cannot end up starting the line."""
        self.assertEqual(self.lead(" * not a list"), "\\* not a list\n")
        self.assertEqual(self.lead("\f*** \v"), "\\*\\*\\*\n")
        self.assertEqual(self.lead("\f~~~ x"), "\\~\\~\\~ x\n")
        document = file_doc("a.py", Section("dependencies", "Dependencies", items=(
            Item("Ratio * ", (Link("numpy"),)),
        )))
        self.assertIn("\n- **Ratio \\*:** `numpy`\n", body(document))

    def test_undecodable_text_is_escaped_as_the_marks_it_becomes(self) -> None:
        self.assertEqual(self.lead("<\udcffdiv> and `<\udcff>` stay text"),
                         "\\<?div> and `<?>` stay text\n")

    def test_tildes_cannot_strike_text_through(self) -> None:
        self.assertEqual(
            self.lead("Takes 1.0~rc1 or 2.0~rc2, not ~~old~~; reads ~/.cfg; a ~ b."),
            r"Takes 1.0\~rc1 or 2.0\~rc2, not \~\~old\~\~; reads \~/.cfg; a ~ b."
            + "\n",
        )

    def test_emphasis_html_and_entities_in_text(self) -> None:
        self.assertEqual(
            self.lead("Calls __init__ with *args on List<Item>, <!-- x --> and "
                      "&amp; or &#35; but snake_case, a * b and AT&T stay."),
            r"Calls \_\_init\_\_ with \*args on List\<Item>, \<!-- x --> and "
            r"\&amp; or \&#35; but snake_case, a * b and AT&T stay." + "\n",
        )

    def test_stray_backticks_and_backslashes(self) -> None:
        self.assertEqual(self.lead("a ` b and C:\\dir\\*"),
                         r"a \` b and C:\\dir\\\*" + "\n")

    def test_injected_links_and_images_are_neutralised(self) -> None:
        self.assertEqual(
            self.lead("See [docs](http://e.x), ![x](http://e.x/p.png) and [r]: x."),
            r"See [docs\](http://e.x), ![x\](http://e.x/p.png) and [r\]: x." + "\n",
        )

    def test_newlines_flatten_and_blank_lines_split_paragraphs(self) -> None:
        self.assertEqual(self.lead("one\ntwo  \r\n# three\n\n\n  four"),
                         "one two # three\n\nfour\n")

    def test_titles_are_escaped_and_keep_a_trailing_hash(self) -> None:
        document = file_doc("pkg/__init__.py", Section(
            "notes", "Notes #", items=(Item("x"),),
        ))
        self.assertEqual(body(document), md(r"""
# pkg/\_\_init\_\_.py

## Notes \#

- x
"""))

    def test_table_cells_escape_pipes_and_flatten_newlines(self) -> None:
        module = Document(
            id="module:", kind=DocKind.MODULE, title="demo", path="index",
            sections=(Section("components", "Components", items=(
                Item("Reads `a | b`\nand c | d.", (Link("x.py", "file:x.py"),)),
            )),),
        )
        page = body(module, file_doc("x.py"))
        self.assertIn(r"| [x.py](x.py.md) | Reads `a \| b` and c \| d. |", page)

    def test_signature_fences_outgrow_backticks_inside(self) -> None:
        nested = SymbolDoc(id="a.py#f.g", name="g", qualname="f.g",
                           kind="function", signature="def g(s='`')")
