class TestInvariants(unittest.TestCase):
    def messy(self) -> Document:
        return file_doc(
            "messy.py",
            Section("purpose", "Purpose", text=(
                "Line one.  \r\nLine two.\t\n\n\n\nPara\u2028three.   ",
            )),
            Section("notes", "Notes", items=(Item("Trailing   "), Item("  Leading")),
                    diagram="graph LR  \n\n\n  a --> b   \r\n"),
            Section("public-surface", "Public surface", symbols=(
                SymbolDoc(id="messy.py#f", name="f", qualname="f", kind="function",
                          signature="def f(\n    a,   \n\n\n    b,\n)",
                          summary="  Sum.  \n\n\n  Twice.  "),
            )),
        )

    def test_whitespace_is_normalised(self) -> None:
        self.assertEqual(body(self.messy()), md("""
# messy.py

Line one. Line two.

Para three.

## Public surface

<a id="sym-f"></a>
### `f`

```python
def f(
    a,

    b,
)
```

Sum.

Twice.

## Notes

```mermaid
graph LR

  a --> b
```

- Trailing
- Leading
"""))

    def test_every_page_is_clean_utf8_with_one_final_newline(self) -> None:
        docset = shop()
        docset.add(self.messy())
        for path, data in MarkdownRenderer().render(docset).items():
            with self.subTest(path=path):
                text = data.decode("utf-8")
                self.assertTrue(text.endswith("\n"))
                self.assertFalse(text.endswith("\n\n"))
                self.assertNotIn("\r", text)
                self.assertNotIn("\n\n\n", text)
                for line in text.split("\n"):
                    self.assertEqual(line, line.rstrip())

    def test_rendering_is_deterministic(self) -> None:
        first = MarkdownRenderer().render(shop())
        self.assertEqual(MarkdownRenderer().render(shop()), first)
        reversed_set = DocSet(project="shop", description="A demo shop.")
        for document in reversed(shop().documents):
            reversed_set.add(document)
        self.assertEqual(MarkdownRenderer().render(reversed_set), first)
        self.assertEqual(list(first), sorted(first))

    def test_undecodable_names_degrade_instead_of_raising(self) -> None:
        pages = MarkdownRenderer().render(DocSet(project="demo", documents=[
            file_doc("bad\udcff.py", Section("purpose", "Purpose", text=("\ud800",))),
            file_doc("odd\ud800.py"),
        ]))
        page = pages["bad\udcff.py.md"].decode("utf-8")
        self.assertIn('title: "bad\\udcff.py"', page)
        self.assertIn("# bad?.py\n\n?\n", page)
        self.assertIn(b"| [bad?.py](bad%FF.py.md) | |", pages["README.md"])
        self.assertIn(b"| [odd?.py](odd%EF%BF%BD.py.md) | |", pages["README.md"])


