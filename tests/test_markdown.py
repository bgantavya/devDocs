def md(text: str) -> str:
    """An expected page, written from the line after the opening quotes."""
    return text.removeprefix("\n")


def sym(qualname: str, kind: str, signature: str = "", summary: str = "",
        **kwargs: Any) -> SymbolDoc:
    return SymbolDoc(
        id=f"src/shop/cart.py#{qualname}",
        name=qualname.rsplit(".", 1)[-1],
        qualname=qualname,
        kind=kind,
        signature=signature,
        summary=summary,
        **kwargs,
    )


def file_doc(relpath: str, *sections: Section, **meta: Any) -> Document:
    meta.setdefault("language", "python")
    return Document(
        id=f"file:{relpath}",
        kind=DocKind.FILE,
        title=relpath,
        path=relpath,
        sections=sections,
        meta=DocMeta(source=relpath, **meta),
    )


def render(
    *documents: Document,
    project: str = "demo",
    description: str = "",
    front_matter: bool = True,
    diagrams: bool = True,
) -> dict[str, str]:
    docset = DocSet(project=project, description=description)
    for document in documents:
        docset.add(document)
    renderer = MarkdownRenderer(front_matter=front_matter, diagrams=diagrams)
    pages = renderer.render(docset)
    return {path: data.decode("utf-8") for path, data in pages.items()}


def body(document: Document, *others: Document, diagrams: bool = True) -> str:
    """`document`'s page without front matter, rendered beside `others`."""
    pages = render(document, *others, front_matter=False, diagrams=diagrams)
    return pages[f"{document.path}.md"]


