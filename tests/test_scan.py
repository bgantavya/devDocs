class TestRepositoryContext(ScanCase):
    def test_subdirectory_scan_applies_the_repository_gitignore(self) -> None:
        self.write(".git/info/exclude", "*.secret\n")
        self.write(".gitignore", "coverage/\n*.local.ts\n")
