"""HTML output: a static documentation site, or one page to print as a book.

Site mode writes a page per document, a home page at `index.html` and shared
files under `assets/`; any static web server, GitHub Pages or a directory on
disk serves it as is. Pages say what the Markdown pages say, in the same
order — lead section, facts, then the rest in `SECTION_ORDER` — and add only
navigation: breadcrumbs, a sidebar and an "On this page" list. Book mode
writes everything into one self-contained `book.html` (stylesheet inlined,
diagrams as inline SVG, nothing fetched) for an external PDF engine: the
home page's overview, then every document in reading order, each starting a
new page, with links turned into in-page anchors. It sets page margins and a
folio, "Page N of M" as the built-in PDF engine prints it, but no page size,
which the engine chooses, or a `@page` rule added to the page.

Names. A document's page is `<path>.html`. The root module's path, `index`,
is the home page's name, so its page is `root.html`; should two documents
still claim one name, the later in reading order gets `-2`, `-3` and so on.
Names that differ only in case or Unicode normalization count as one, as
macOS stores them as one file by default, and Windows those differing in
case: a document at path `Root` gets `Root-2.html`, beside the root
module's `root.html`, not a file that page overwrites.
`.nojekyll` keeps GitHub Pages from hiding pages whose names start with an
underscore, such as `__init__.py.html`. A section heading's id is its key; a
symbol's is `model.anchor`, the anchor Markdown gives it. In the book every
id is prefixed with its document's chapter id and `--`, and headings sit one
level lower under the book's title.

Navigation. The sidebar lists the architecture and every module, and opens
only the current page's module to its files: the whole tree on every page
would make the site's size grow with the square of its file count. The home
page and the module pages list every file, and an optional script filters
all pages by title and summary from one generated index, `assets/pages.js`;
a script and not JSON, because browsers refuse `fetch` to pages opened from
disk. Both scripts open with `@generated`, the marker `devdocs.scan` reads,
so a site inside a project is never documented as its JavaScript, even once
the manifest that lists the site's files is lost.

Safety. Every string in a DocSet comes from source code or a model, so all of
it is escaped, in text and attributes alike, and characters HTML cannot carry
become U+FFFD. A link is only ever a relative path to a generated page,
percent-encoded so no file name can pass for a scheme, plus an id known to be
on that page: an anchor the target does not carry is dropped, not left
dangling. A Content-Security-Policy allows same-origin stylesheets and
scripts only, and no page carries inline script, style attributes or event
handlers. The book must inline its stylesheet, so its policy allows inline
style and nothing else: no script, no fetch.

Determinism. Pages carry no timestamp, cost or count, and every list has a
fixed order, so the same DocSet renders to the same bytes. A document's page
carries its own provenance only; the run's generator and git commit are named
once, on the home page (and in the book), so a regeneration at a new commit
rewrites the home page and the pages whose documents changed, not the site.
"""

