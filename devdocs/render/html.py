class HtmlRenderer:
    """Renders a DocSet as a static site, or with `book` as one page to print."""

    format = "html"

    def __init__(self, *, book: bool = False) -> None:
        self.book = book

    def render(self, docset: DocSet) -> dict[str, bytes]:
        """Every file as bytes, keyed by POSIX path under the out dir, sorted."""
        site = _Site(docset, book=self.book)
        if self.book:
            return {BOOK: site.book()}
        files = {site.places[d.id]: site.page(d) for d in site.order}
        files[HOME] = site.home()
        files[_STYLE] = _asset("style.css")
        files[_SCRIPT] = _asset("filter.js")
        files[_INDEX] = site.search_index()
        files[_NOJEKYLL] = b""
        return dict(sorted(files.items()))


class _Site:
    """What every page needs to know of the others: where each document is,
    the anchors its page carries and the module each file belongs to."""

    def __init__(self, docset: DocSet, *, book: bool) -> None:
        self.docset = docset
        self.in_book = book
        self.project = docset.project or "Documentation"
        self.index = {document.id: document for document in docset.documents}
        self.order = docset.sorted()
        self.architecture = docset.by_kind(DocKind.ARCHITECTURE)
        self.modules = docset.by_kind(DocKind.MODULE)
        self.files = docset.by_kind(DocKind.FILE)
        self.anchors = {document.id: _anchors(document) for document in self.order}
        self.places = _chapters(self.order) if book else _pages(self.order)

        self.by_source: dict[str, Document] = {}
        for module in self.modules:
            self.by_source.setdefault(module.meta.source, module)
        self.owner: dict[str, Document] = {}
        self.contents: dict[str, list[Document]] = {m.id: [] for m in self.modules}
        for file in self.files:
            owner = self._nearest(posixpath.dirname(file.meta.source or file.title))
            if owner is not None:
                self.owner[file.id] = owner
                self.contents[owner.id].append(file)
        self.loose = [file for file in self.files if file.id not in self.owner]

    def _nearest(self, directory: str) -> Document | None:
        """The module of `directory`, or else of its nearest ancestor."""
        while True:
            module = self.by_source.get(directory)
            if module is not None:
                return module
            parent = posixpath.dirname(directory)
            if parent == directory:
                return None
            directory = parent

    def trail(self, document: Document) -> list[Document]:
        """The modules above `document`, outermost first: a file's own module
        and the modules above that, or a module's ancestors."""
        if document.kind is DocKind.MODULE:
            return self._ancestors(document)
        owner = self.owner.get(document.id)
        return [*self._ancestors(owner), owner] if owner is not None else []

    def _ancestors(self, module: Document) -> list[Document]:
        chain: list[Document] = []
        source = module.meta.source
        while (parent := posixpath.dirname(source)) != source:
            found = self._nearest(parent)
            if found is None:
                break
            chain.append(found)
            source = found.meta.source
        return chain[::-1]

    # -- site pages --------------------------------------------------------

    def page(self, document: Document) -> bytes:
        page = _Page(self, here=self.places[document.id],
                     language=document.meta.language)
        intro, body = page.content(document)
        lead = [
            self.crumbs(page, document),
            f"<h1>{_inline(document.title)}</h1>",
            f'<p class="provenance">{_provenance(document)}</p>',
        ]
        return self.sheet(
            page,
            title=f"{_plain(document.title)} · {_line(self.project)}",
            description=document.summary,
            meta=_document_meta(document, self.docset),
            intro=lead + intro,
            body=body,
            current=document,
        )

    def home(self) -> bytes:
        page = _Page(self, here=HOME)
        intro, body = self.overview(page)
        return self.sheet(
            page,
            title=_line(self.project),
            description=self.docset.description,
            meta=_run_meta(self.docset),
            intro=intro,
            body=body,
            current=None,
        )

    def overview(self, page: _Page) -> tuple[list[str], list[str]]:
        """The home page's content, which also opens the book."""
        intro = [f"<h1>{_inline(self.project)}</h1>",
                 *_paragraphs(self.docset.description)]
        if self.architecture:
            document = self.architecture[0]
            line = page.link(Link("Architecture", document.id))
            summary = _inline(document.summary)
            intro.append(f"<p>{line} — {summary}</p>" if summary else f"<p>{line}</p>")
        body: list[str] = []
        if self.modules:
            body.append(page.section("modules", "Modules", [_table(
                ("Module", "Summary"),
                [("", (page.link(Link(d.meta.source or "(root)", d.id)),
                       _inline(d.summary))) for d in self.modules],
            )]))
        if self.files:
            body.append(page.section("files", "Files", [_table(
                ("File", "Summary"),
                [("", (page.link(Link(d.meta.source or d.title, d.id)),
                       _inline(d.summary))) for d in self.files],
            )]))
        body.append(f'<p class="colophon">{_FOOTER}</p>')
        return intro, body

    def sheet(
        self,
        page: _Page,
        *,
        title: str,
        description: str,
        meta: Sequence[tuple[str, str]],
        intro: Sequence[str],
        body: Sequence[str],
        current: Document | None,
    ) -> bytes:
        """A whole site page around its content."""
        toc = page.toc()
        main = ' class="has-toc"' if toc else ""
        return _bytes([
            "<!DOCTYPE html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            f'<meta http-equiv="Content-Security-Policy" content="{_CSP}">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            '<meta name="color-scheme" content="light dark">',
            f"<title>{escape(title)}</title>",
            *_metas(description, meta),
            f'<link rel="stylesheet" href="{page.href_to(_STYLE)}">',
            f'<script src="{page.href_to(_INDEX)}" defer></script>',
            f'<script src="{page.href_to(_SCRIPT)}" defer></script>',
            "</head>",
            "<body>",
            '<a class="skip-link" href="#content">Skip to content</a>',
            '<header class="masthead">',
            f'<a class="brand" href="{page.href_to(HOME)}">'
            f"{escape(_line(self.project))}</a>",
            '<a class="menu-link" href="#site-nav">Menu</a>',
            "</header>",
            '<div class="layout">',
            f'<main id="content" tabindex="-1"{main}>',
            '<div class="intro">',
            *intro,
            "</div>",
            *([toc] if toc else []),
            '<div class="body">',
            *body,
            "</div>",
            "</main>",
            self.sidebar(page, current),
            "</div>",
            "</body>",
            "</html>",
        ])

    def crumbs(self, page: _Page, document: Document) -> str:
        """Home, then each module above `document`, each named relative to
        the one before it, then the page itself."""
        items = [page.crumb(HOME, self.project)]
        above = ""
        for module in self.trail(document):
            source = module.meta.source
            items.append(page.crumb(self.places[module.id],
                                    _within(source, above) if source else "(root)"))
            above = source
        if document.kind is DocKind.ARCHITECTURE:
            name = document.title
        elif document.kind is DocKind.MODULE and not document.meta.source:
            name = "(root)"
        else:
            name = _within(document.meta.source or document.title, above)
        items.append(f'<li aria-current="page">{_breakable(_line(name))}</li>')
        return ('<nav class="crumbs" aria-label="Breadcrumb"><ol>'
                + "".join(items) + "</ol></nav>")

    def sidebar(self, page: _Page, current: Document | None) -> str:
        """Home, the architecture and every module; the current page's module
        is opened to its files, and the current page is marked."""
        opened = current
        if current is not None and current.kind is not DocKind.MODULE:
            opened = self.owner.get(current.id)
        lines = [
            '<nav class="sidebar" id="site-nav" aria-label="Documentation">',
            '<ul class="nav">',
            page.nav_item(HOME, "Home"),
            *(page.nav_item(self.places[d.id], d.title) for d in self.architecture),
            "</ul>",
        ]
        if self.modules:
            lines.append('<p class="nav-label" id="nav-modules">Modules</p>')
            lines.append('<ul class="nav" aria-labelledby="nav-modules">')
            for module in self.modules:
                files = ""
                if module is opened and self.contents[module.id]:
                    files = "<ul>" + "".join(
                        page.nav_item(self.places[f.id],
                                      _within(f.meta.source or f.title,
                                              module.meta.source))
                        for f in self.contents[module.id]
                    ) + "</ul>"
                lines.append(page.nav_item(
                    self.places[module.id], module.meta.source or "(root)",
                    children=files, opened=module is opened,
                ))
            lines.append("</ul>")
        if self.loose:
            lines.append('<p class="nav-label" id="nav-files">Files</p>')
            lines.append('<ul class="nav" aria-labelledby="nav-files">')
            lines.extend(page.nav_item(self.places[f.id], f.meta.source or f.title)
                         for f in self.loose)
            lines.append("</ul>")
        lines.append("</nav>")
        return "\n".join(lines)

    def search_index(self) -> bytes:
        """`assets/pages.js`: every page's title, path and summary, for the
        filter script; one page per line, so a regeneration diffs cleanly."""
        entries = [
            json.dumps([_plain(d.title), url_path(self.places[d.id]),
                        _plain(d.summary)])
            for d in self.order
        ]
        return (_INDEX_HEAD + "window.devdocsPages = [\n" + ",\n".join(entries)
                + "\n];\n").encode()

    # -- the book ----------------------------------------------------------

    def book(self) -> bytes:
        cover = _Page(self, chapter="home")
        intro, body = self.overview(cover)
        style = _asset("style.css").decode("utf-8").rstrip("\n")
        return _bytes([
            "<!DOCTYPE html>",
            '<html lang="en">',
            "<head>",
            '<meta charset="utf-8">',
            f'<meta http-equiv="Content-Security-Policy" content="{_BOOK_CSP}">',
            '<meta name="viewport" content="width=device-width, initial-scale=1">',
            '<meta name="color-scheme" content="light dark">',
            f"<title>{escape(_line(self.project))}</title>",
            *_metas(self.docset.description, _run_meta(self.docset)),
            "<style>",
            style,
            "</style>",
            "</head>",
            '<body class="book">',
            "<main>",
            '<section class="cover" id="home">',
            *intro,
            *body,
            "</section>",
            *(self.chapter(document) for document in self.order),
            "</main>",
            "</body>",
            "</html>",
        ])

    def chapter(self, document: Document) -> str:
        place = self.places[document.id]
        page = _Page(self, chapter=place, level=2, language=document.meta.language)
        intro, body = page.content(document)
        return "\n".join([
            f'<article class="document" id="{place}">',
            f"<h2>{_inline(document.title)}</h2>",
            f'<p class="provenance">{_provenance(document)}</p>',
            *intro,
            *body,
            "</article>",
        ])


class _Page:
    """Rendering state for one site page or one chapter of the book: where it
    is, the heading level of its title, and the ids it has handed out."""

    def __init__(
        self,
        site: _Site,
        *,
        here: str = "",
        chapter: str = "",
        level: int = 1,
        language: str = "",
    ) -> None:
        self.site = site
        self.here = here                 # the page's file; "" in the book
        self.directory = posixpath.dirname(here)
        self.chapter = chapter           # the chapter's id; "" on the site
        self.level = level
        self.language = _slug(language)
        self.taken: set[str] = set() if chapter else set(_SITE_IDS)
        self.outline: list[tuple[str, str, list[tuple[str, str]]]] = []
        self.entries: list[tuple[str, str]] = []    # symbols since the last section
        self.diagrams = 0

    # -- ids and links -----------------------------------------------------

    def ref(self, name: str) -> str:
        """The id `name` gets in the output: prefixed in a book chapter."""
        return f"{self.chapter}--{name}" if self.chapter else name

    def claim(self, name: str) -> str:
        """`name` as an id, once per page; "" when it is already taken."""
        if name in self.taken:
            return ""
        self.taken.add(name)
        return self.ref(name)

    def unique(self, name: str, *suffixes: str) -> str:
        """The first free one of `name`, `name-2`, ..., together with the ids
        it makes by adding each of `suffixes`; all are taken from now on."""
        candidate, count = name, 1
        while any(n in self.taken
                  for n in (candidate, *(f"{candidate}-{s}" for s in suffixes))):
            count += 1
            candidate = f"{name}-{count}"
        self.taken.add(candidate)
        self.taken.update(f"{candidate}-{s}" for s in suffixes)
        return candidate

    def href_to(self, path: str) -> str:
        """A generated file's address from here, ready for an attribute."""
        return escape(url_path(relpath(path, self.directory)))

    def href(self, link: Link) -> str | None:
        """Where `link` points from here; None when it points nowhere."""
        target = self.site.index.get(link.target) if link.target else None
        if target is None:
            return None
        anchor = link.anchor if link.anchor in self.site.anchors[target.id] else ""
        place = self.site.places[target.id]
        if self.site.in_book:
            return f"#{place}--{anchor}" if anchor else f"#{place}"
        if anchor and place == self.here:
            return f"#{anchor}"
        page = url_path(relpath(place, self.directory))
        return page + (f"#{anchor}" if anchor else "")

    def link(self, link: Link) -> str:
        href = self.href(link)
        if href is None:
            return _inline(link.text)
        text = link.text or self.site.index[link.target].title
        return f'<a href="{escape(href)}">{_inline(text)}</a>'

    def links(self, links: Iterable[Link]) -> str:
        return ", ".join(text for text in map(self.link, links) if text)

    def crumb(self, path: str, label: str) -> str:
        return f'<li><a href="{self.href_to(path)}">{_breakable(_line(label))}</a></li>'

    def nav_item(
        self, path: str, label: str, *, children: str = "", opened: bool = False
    ) -> str:
        current = ' aria-current="page"' if path == self.here else ""
        kind = ' class="open"' if opened else ""
        return (f'<li{kind}><a href="{self.href_to(path)}"{current}>'
                f"{_breakable(_line(label))}</a>{children}</li>")

    # -- the page outline --------------------------------------------------

    def section(self, key: str, heading: str, blocks: Sequence[str]) -> str:
        """A headed section, listed under "On this page" with its symbols."""
        name = self.unique(_slug(key) or "section")
        tag = f"h{self.level + 1}"
        self.outline.append((name, heading, self.entries))
        self.entries = []
        return "\n".join(
            ["<section>", f'<{tag} id="{self.ref(name)}">{heading}</{tag}>',
             *blocks, "</section>"]
        )

    def toc(self) -> str:
        """The "On this page" list: sections, and the symbols under each."""
        if not self.outline:
            return ""
        items = []
        for name, heading, symbols in self.outline:
            nested = "".join(
                f'<li><a href="#{escape(ident)}">{label}</a></li>'
                for ident, label in symbols
            )
            items.append(f'<li><a href="#{escape(name)}">{heading}</a>'
                         + (f"<ul>{nested}</ul>" if nested else "") + "</li>")
        return "\n".join([
            '<nav class="toc" aria-labelledby="toc-title">',
            '<p class="toc-title" id="toc-title">On this page</p>',
            "<ul>",
            *items,
            "</ul>",
            "</nav>",
        ])

    # -- documents ---------------------------------------------------------

    def content(self, document: Document) -> tuple[list[str], list[str]]:
        """The lead section and the facts, then every other section in
        `SECTION_ORDER`, unknown keys last in the order given."""
        lead = _LEAD.get(document.kind, "purpose")
        intro: list[str] = []
        for section in document.sections:
            if section.key == lead:
                intro.extend(self.body(section, self.level + 1))
        self.outline.extend((ident, label, []) for ident, label in self.entries)
        self.entries = []
        for section in document.sections:
            if section.key == _FACTS:
                intro.extend(self.facts(section))

        order = SECTION_ORDER.get(document.kind, ())
        rank = {key: position for position, key in enumerate(order)}
        rest = sorted(
            (s for s in document.sections if s.key not in (lead, _FACTS)),
            key=lambda section: rank.get(section.key, len(rank)),
        )
        body: list[str] = []
        for section in rest:
            blocks = self.body(section, self.level + 2)
            if blocks:
                heading = _inline(section.title or _titled(section.key))
                body.append(self.section(section.key, heading, blocks))
        return intro, body

    def body(self, section: Section, level: int) -> list[str]:
        """A section's blocks: diagram, paragraphs, items, then symbols, whose
        headings are at `level`."""
        blocks: list[str] = []
        if section.diagram.strip():
            blocks.append(self.diagram(section))
        for text in section.text:
            blocks.extend(_paragraphs(text))
        if section.items:
            blocks.append(self.items(section))
        if section.symbols:
            blocks.extend(self.symbols(section.symbols, level))
        return [block for block in blocks if block]

    def diagram(self, section: Section) -> str:
        """The diagram as inline SVG; Mermaid it cannot read, as source.

        On screen a drawing keeps its size, so its labels stay legible, and
        scrolls sideways when wider than the column; print scales it to the
        page. The column's width is the screen's to decide, so any drawing
        wider than a 320px phone's column takes focus, for a keyboard to
        scroll it; on a screen where it fits, that is a tab stop with nothing
        to scroll.
        """
        graph = parse_mermaid(section.diagram)
        if graph is None:
            return _pre(section.diagram, "mermaid")
        self.diagrams += 1
        name = self.unique(f"diagram-{self.diagrams}", "arrow", "title", "desc")
        title = f"{_plain(section.title or _titled(section.key))} diagram"
        drawing = layout(graph, font_size=_DIAGRAM_FONT)
        svg = to_svg(
            drawing,
            font_size=_DIAGRAM_FONT,
            margin=_DIAGRAM_MARGIN,
            ident=self.ref(name),
            title=title,
            description=_plain(describe(graph)),
        )
        if drawing.width + 2 * _DIAGRAM_MARGIN <= _PHONE_COLUMN:
            return f'<figure class="figure">{svg}</figure>'
        label = self.ref(f"{name}-title")
        return (f'<figure class="figure" tabindex="0" aria-labelledby="{label}">'
                f"{svg}</figure>")

    def facts(self, section: Section) -> list[str]:
        """The facts as one inline list, plus any paragraphs they carry."""
        parts: list[str] = []
        for item in section.items:
            part = _labelled(_inline(item.text), self.links(item.links))
            if part:
                parts.append(f"<li>{part}</li>")
        blocks = [f'<ul class="facts">{"".join(parts)}</ul>'] if parts else []
        for text in section.text:
            blocks.extend(_paragraphs(text))
        return blocks

    def items(self, section: Section) -> str:
        key = section.key
        if key == "components":
            return _table(("File", "Summary"), [
                ("", (self.link(item.links[0]) if item.links else "",
                      _inline(item.text)))
                for item in section.items
            ])
        if key == "component-map":
            return _table(("Component", "Responsibility", "Depends on"), [
                ("", (self.link(item.links[0]) if item.links else "",
                      _inline(item.text), self.links(item.links[1:])))
                for item in section.items
            ])
        if key == "dependencies":
            lines = [self.dependency(item) for item in section.items]
        elif key == "entry-points":
            lines = [self.entry(item) for item in section.items]
        else:
            line_ref = key == "known-issues"
            lines = [self.bullet(item, line_ref=line_ref) for item in section.items]
        listed = [f"<li>{line}</li>" for line in lines if line]
        if not listed:
            return ""
        tag = "ol" if section.ordered or key == "data-flow" else "ul"
        return "\n".join([f"<{tag}>", *listed, f"</{tag}>"])

    def bullet(self, item: Item, *, line_ref: bool) -> str:
        """`text — links`; with `line_ref`, a positive line leads as `L12:`."""
        text = _inline(item.text)
        if line_ref and item.line > 0:
            text = f"L{item.line}: {text}" if text else f"L{item.line}"
        return _dashed(text, self.links(item.links))

    def dependency(self, item: Item) -> str:
        """`label: targets`, where a target-less link names a package."""
        rendered = ", ".join(
            text
            for text in (
                self.link(link) if link.target else _code(link.text)
                for link in item.links
            )
            if text
        )
        return _labelled(_inline(item.text), rendered)

    def entry(self, item: Item) -> str:
        return _dashed(self.links(item.links), _inline(item.text))

    # -- symbols -----------------------------------------------------------

    def symbols(self, symbols: Sequence[SymbolDoc], level: int) -> list[str]:
        """One block per symbol, then every constant in a single table."""
        blocks = [self.symbol(s, level) for s in symbols if s.kind != "constant"]
        constants = [s for s in symbols if s.kind == "constant"]
        if constants:
            blocks.append(_table(("Constant", "Definition"), [
                (self.claim(s.anchor),
                 (_code(s.name or s.qualname), self.definition(s)))
                for s in constants
            ]))
        return blocks

    def symbol(self, symbol: SymbolDoc, level: int) -> str:
        ident = self.claim(symbol.anchor)
        name = _code(symbol.name or symbol.qualname)
        if ident:
            self.entries.append((ident, name))
        tag = f"h{min(level, 6)}"
        heading = name
        if symbol.is_async:
            heading += ' <span class="async">(async)</span>'
        attribute = f' id="{ident}"' if ident else ""
        blocks = [f"<{tag}{attribute}>{heading}</{tag}>"]
        if symbol.signature.strip():
            blocks.append(_pre(symbol.signature, self.language))
        blocks.extend(_paragraphs(symbol.summary))
        bases = ", ".join(_code(base) for base in symbol.bases if base)
        if bases:
            blocks.append(f'<p class="detail">Bases: {bases}</p>')
        decorators = ", ".join(
            _code(d if d.startswith("@") else f"@{d}") for d in symbol.decorators if d
        )
        if decorators:
            blocks.append(f'<p class="detail">Decorators: {decorators}</p>')
        members = self.members(symbol.members)
        if members:
            blocks.append(members)
        return "\n".join(['<div class="symbol">', *blocks, "</div>"])

    def members(self, members: Sequence[SymbolDoc]) -> str:
        """Members as a list, nested members beneath them. A member with
        nothing to show gets no empty item; its own members take its place."""
        items = self._member_items(members)
        if not items:
            return ""
        return "\n".join(['<ul class="members">', *items, "</ul>"])

    def _member_items(self, members: Sequence[SymbolDoc]) -> list[str]:
        items: list[str] = []
        for member in members:
            shown = _dashed(*_member(member))
            if not shown:
                items.extend(self._member_items(member.members))
                continue
            ident = self.claim(member.anchor)
            attribute = f' id="{ident}"' if ident else ""
            items.append(f"<li{attribute}>{shown}{self.members(member.members)}</li>")
        return items

    def definition(self, constant: SymbolDoc) -> str:
        return _dashed(_code(constant.signature), _inline(constant.summary))


# -- names and anchors -----------------------------------------------------


def _pages(documents: Sequence[Document]) -> dict[str, str]:
    """Each document's page file: `<path>.html`, the root module's
    `root.html`, and a `-2`, `-3` suffix for a name already taken, as a file
    system that ignores case and normalization would see it."""
    taken = {folded(HOME)}
    pages: dict[str, str] = {}
    for document in documents:
        root = document.kind is DocKind.MODULE and document.path == Layout.module("")
        stem = ROOT_MODULE.removesuffix(".html") if root else document.path
        pages[document.id] = claim(stem, ".html", taken)
    return pages


def _chapters(documents: Sequence[Document]) -> dict[str, str]:
    """Each document's chapter id in the book, from its document id."""
    taken = set(_BOOK_IDS)
    chapters: dict[str, str] = {}
    for document in documents:
        stem = _slug(document.id) or "document"
        name, count = stem, 1
        while name in taken:
            count += 1
            name = f"{stem}-{count}"
        taken.add(name)
        chapters[document.id] = name
    return chapters


def _anchors(document: Document) -> frozenset[str]:
    """The symbol anchors `document`'s page carries: every symbol it shows.

    Facts sections show no symbols and a constant shows no members; a member
    with nothing to show carries no anchor, though its own members may.
    """
    found: set[str] = set()

    def visit(members: Iterable[SymbolDoc]) -> None:
        for member in members:
            if any(_member(member)):
                found.add(member.anchor)
            visit(member.members)

    for section in document.sections:
        if section.key == _FACTS:
            continue
        for symbol in section.symbols:
            found.add(symbol.anchor)
            if symbol.kind != "constant":
                visit(symbol.members)
    return frozenset(found)


def _member(member: SymbolDoc) -> tuple[str, str]:
    """A member's code and summary as HTML; both "" when it shows nothing."""
    code = _code(member.signature or member.name or member.qualname)
    return code, _inline(member.summary)


def _slug(text: str) -> str:
    return _NOT_ID.sub("-", text).strip("-")


def _within(path: str, directory: str) -> str:
    """`path` relative to `directory` when it lies inside it."""
    if directory and path.startswith(directory + "/"):
        return path[len(directory) + 1:]
    return path


# -- metadata --------------------------------------------------------------


def _document_meta(document: Document, docset: DocSet) -> list[tuple[str, str]]:
    """The document's provenance as `devdocs:` meta tags, in a fixed order;
    empty values and zero counts are left out, as in Markdown front matter.

    The run's generator and git commit are the home page's to name: on every
    page, a regeneration at a new commit would rewrite every page.
    """
    meta = document.meta
    fields: list[tuple[str, str | int]] = [
        ("id", document.id),
        ("kind", str(document.kind)),
        ("source", meta.source),
        ("source_hash", meta.source_hash),
        ("language", meta.language),
        ("mode", str(meta.mode)),
        ("model", meta.model),
        ("tier", meta.tier),
        ("input_tokens", meta.input_tokens),
        ("output_tokens", meta.output_tokens),
        ("confidence", "" if meta.confidence == "exact" else meta.confidence),
        *(("note", note) for note in meta.notes),
        ("schema", docset.schema_version),
    ]
    return [
        (key, str(value))
        for key, value in fields
        if (value > 0 if isinstance(value, int) else value)
    ]


def _run_meta(docset: DocSet) -> list[tuple[str, str]]:
    run = docset.run
    fields = (
        ("schema", docset.schema_version),
        ("generator", run.generator if run else ""),
        ("git_commit", run.git_commit if run else ""),
    )
    return [(key, value) for key, value in fields if value]


def _metas(description: str, fields: Iterable[tuple[str, str]]) -> list[str]:
    lines: list[str] = []
    summary = _plain(description)
    if summary:
        lines.append(f'<meta name="description" content="{escape(summary)}">')
    lines.extend(
        f'<meta name="devdocs:{key}" content="{escape(_line(value))}">'
        for key, value in fields
    )
    return lines


def _provenance(document: Document) -> str:
    meta = document.meta
    if meta.mode == Mode.PROSE:
        writer = escape(_line(meta.model)) or "a model"
        return f"Written from source by devdocs; prose by {writer}."
    return "Written from source by devdocs; no model prose."


# -- blocks ----------------------------------------------------------------


def _titled(key: str) -> str:
    return key.replace("-", " ").strip().capitalize()


def _dashed(first: str, second: str) -> str:
    """`first — second`, or whichever of them is not empty."""
    return f"{first} — {second}" if first and second else first or second


def _labelled(label: str, rest: str) -> str:
    """`label: rest` with the label strong, or whichever is not empty."""
    return f"<strong>{label}:</strong> {rest}" if label and rest else label or rest


def _paragraphs(text: str) -> list[str]:
    """Each blank-line-separated part of `text` as a paragraph."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    found = (_inline(part) for part in _PARAGRAPH.split(text))
    return [f"<p>{paragraph}</p>" for paragraph in found if paragraph]


def _table(
    header: Sequence[str], rows: Iterable[tuple[str, Sequence[str]]]
) -> str:
    """A table of already-rendered cells, each row as (id, cells); a row with
    neither is dropped, and "" stands for a table with no rows left."""
    body = [(ident, cells) for ident, cells in rows if ident or any(cells)]
    if not body:
        return ""
    head = "".join(f'<th scope="col">{cell}</th>' for cell in header)
    lines = ["<table>", f"<thead><tr>{head}</tr></thead>", "<tbody>"]
    for ident, cells in body:
        attribute = f' id="{ident}"' if ident else ""
        lines.append(f"<tr{attribute}>"
                     + "".join(f"<td>{cell}</td>" for cell in cells) + "</tr>")
    lines.extend(["</tbody>", "</table>"])
    return "\n".join(lines)


def _pre(code: str, language: str = "") -> str:
    """A code block, lines kept and trailing spaces dropped."""
    lines = (line.rstrip() for line in _clean(code).splitlines())
    body = "\n".join(lines).strip("\n")
    kind = f' class="language-{language}"' if language else ""
    return f"<pre><code{kind}>{escape(body)}</code></pre>"


def _bytes(lines: Iterable[str]) -> bytes:
    return ("\n".join(lines) + "\n").encode("utf-8", "replace")


@functools.cache
def _asset(name: str) -> bytes:
    """A file packaged in `devdocs/render/assets`, with LF line ends."""
    resource = resources.files("devdocs.render") / "assets" / name
    return resource.read_bytes().replace(b"\r\n", b"\n")


# -- inline text -----------------------------------------------------------


def _clean(text: str) -> str:
    """`text` with the characters HTML cannot carry made U+FFFD: controls
    other than whitespace and line breaks, lone surrogates, non-characters."""
    return _UNSAFE.sub("\ufffd", text)


def _line(text: str) -> str:
    """`text` as one line of plain text, whitespace runs made single spaces."""
    return " ".join(_clean(text).split())


def _inline(text: str) -> str:
    """`text` as one line of HTML: escaped, with code spans as `<code>`."""
    parts: list[str] = []
    for code, chunk in code_spans(_clean(text).strip()):
        if code:
            parts.append(f"<code>{escape(code_text(chunk))}</code>")
        else:
            parts.append(_breakable(_BREAK.sub(" ", chunk)))
    return "".join(parts)


def _breakable(text: str) -> str:
    """`text` escaped, free to wrap after each `/`, so a path on a phone breaks
    between its parts rather than inside one."""
    return escape(text).replace("/", "/<wbr>")


def _plain(text: str) -> str:
    """`text` as one line of plain text, code spans without their backticks."""
    parts = (code_text(chunk) if code else chunk
             for code, chunk in code_spans(_clean(text)))
    return " ".join("".join(parts).split())


def _code(text: str) -> str:
    """`text` as one code element on one line; "" for no text."""
    text = " ".join(_clean(text).splitlines())
    return f"<code>{escape(text)}</code>" if text else ""
