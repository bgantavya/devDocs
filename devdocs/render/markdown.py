"""Markdown output: one page per document, plus a README index.

GitHub-flavoured Markdown, readable as plain text and rendered well by GitHub,
GitLab and most doc sites. Diagrams are Mermaid code blocks, which those hosts
draw natively. Front matter carries the document's metadata so tools can read
provenance without parsing prose.

Text from parsers and models is escaped wherever it would otherwise become
Markdown structure — a heading, a list, a table column, an emphasis pair, a
link — while code spans pass through untouched, so no docstring can reshape
the page it lands on. Links are relative paths between pages, so the output
reads the same on a code host, in a static site or straight from disk. Pages
carry no counts, costs or timestamps: an unchanged source renders to
identical bytes, and a regeneration diffs only where something changed.
"""

from __future__ import annotations

import json
import posixpath
import re
from collections.abc import Iterable, Mapping, Sequence

from devdocs.render.model import (
    SECTION_ORDER,
    DocKind,
    DocSet,
    Document,
    Item,
    Layout,
    Link,
    Section,
    SymbolDoc,
)
from devdocs.render.text import code_spans, relpath, url_path

__all__ = ["MarkdownRenderer"]

_LEAD = {
    DocKind.FILE: "purpose",
    DocKind.MODULE: "purpose",
    DocKind.ARCHITECTURE: "overview",
}
_FACTS = "facts"
_FENCE_LANGUAGE = {"typescript": "ts", "javascript": "js"}
_FOOTER = "Generated by devdocs; edit the source, not these pages."

_BACKTICKS = re.compile(r"`+")
_BREAK = re.compile(r"[ \t]*(?:\r\n|[\n\r\v\f\x1c-\x1e\x85\u2028\u2029])\s*")
_PARAGRAPH = re.compile(r"\n[ \t]*\n\s*")
_SPECIAL = re.compile(r"\*+|_+|~+|[\\`<&\[\]]")
_ENTITY = re.compile(
    r"&(?:#[0-9]{1,7}|#[xX][0-9a-fA-F]{1,6}|[A-Za-z][A-Za-z0-9]{1,31});"
)
_BLOCK = re.compile(
    r"[#>]|[-+](?=\s|$)|-(?=-)|\[[ xX]\](?=\s|$)|[0-9]{1,9}(?=[.)](?:\s|$))"
)
_CLOSING = re.compile(r"(^|\s)(#+)$")
_INFO = re.compile(r"[\s`]+")
_SURROGATE = re.compile("[\ud800-\udfff]")


class MarkdownRenderer:
    """Renders each document as one page and the project index as README.md."""

    format = "markdown"
    extension = ".md"

    def __init__(self, *, front_matter: bool = True, diagrams: bool = True) -> None:
        self.front_matter = front_matter
        self.diagrams = diagrams

    def render(self, docset: DocSet) -> dict[str, bytes]:
        """Every page as UTF-8 bytes, keyed by POSIX path under the out dir.

        The home page carries no front matter, being no document, and is
        rendered last so it keeps README.md should a document's path land there.
        """
        index = {document.id: document for document in docset.documents}
        pages = {
            f"{document.path}{self.extension}": self._document(docset, index, document)
            for document in docset.sorted()
        }
        pages[f"{Layout.home()}{self.extension}"] = self._home(docset, index)
        return dict(sorted(pages.items()))

    def _document(
        self, docset: DocSet, index: Mapping[str, Document], document: Document
    ) -> bytes:
        page = _Page(
            index,
            document.path,
            extension=self.extension,
            language=document.meta.language,
            diagrams=self.diagrams,
        )
        blocks: list[str] = []
        if self.front_matter:
            blocks.append(_front_matter(document, docset.schema_version))
        blocks.append(_heading(1, document.title))

        lead = _LEAD.get(document.kind, "purpose")
        for section in document.sections:
            if section.key == lead:
                blocks.extend(page.body(section))
        for section in document.sections:
            if section.key == _FACTS:
                blocks.extend(page.facts(section))

        order = SECTION_ORDER.get(document.kind, ())
        rank = {key: position for position, key in enumerate(order)}
        rest = sorted(
            (s for s in document.sections if s.key not in (lead, _FACTS)),
            key=lambda section: rank.get(section.key, len(rank)),
        )
        for section in rest:
            body = page.body(section)
            if body:
                blocks.append(_heading(2, section.title or _titled(section.key)))
                blocks.extend(body)
        return _finish(blocks)

    def _home(self, docset: DocSet, index: Mapping[str, Document]) -> bytes:
        page = _Page(index, Layout.home(), extension=self.extension)
        blocks = [_heading(1, docset.project or "Documentation")]
        blocks.extend(_paragraphs(docset.description))

        architecture = docset.by_kind(DocKind.ARCHITECTURE)
        if architecture:
            document = min(architecture, key=lambda d: d.path)
            line = page.link(Link("Architecture", document.id))
            summary = _inline(document.summary)
            blocks.append(f"{line} — {summary}" if summary else line)

        modules = sorted(
            docset.by_kind(DocKind.MODULE), key=lambda d: (d.meta.source, d.path)
        )
        if modules:
            blocks.append(_heading(2, "Modules"))
            blocks.append(_table(("Module", "Summary"), [
                (page.link(Link(d.meta.source or "(root)", d.id)), _inline(d.summary))
                for d in modules
            ]))

        files = sorted(
            docset.by_kind(DocKind.FILE),
            key=lambda d: (d.meta.source or d.title, d.path),
        )
        if files:
            blocks.append(_heading(2, "Files"))
            blocks.append(_table(("File", "Summary"), [
                (page.link(Link(d.meta.source or d.title, d.id)), _inline(d.summary))
                for d in files
            ]))

        blocks.append(_FOOTER)
        return _finish(blocks)


class _Page:
    """Rendering state for one page: where it sits and which anchors it holds."""

    def __init__(
        self,
        index: Mapping[str, Document],
        path: str,
        *,
        extension: str,
        language: str = "",
        diagrams: bool = True,
    ) -> None:
        self.index = index
        self.path = path
        self.directory = posixpath.dirname(path) or "."
        self.extension = extension
        self.language = _FENCE_LANGUAGE.get(language, language)
        self.diagrams = diagrams
        self.anchors: set[str] = set()

    # -- links -------------------------------------------------------------

    def href(self, link: Link) -> str | None:
        """Where `link` points from this page; None when it points nowhere."""
        target = self.index.get(link.target) if link.target else None
        if target is None:
            return None
        fragment = f"#{url_path(link.anchor)}" if link.anchor else ""
        if fragment and target.path == self.path:
            return fragment
        page = relpath(f"{target.path}{self.extension}", self.directory)
        return url_path(page) + fragment

    def link(self, link: Link) -> str:
        href = self.href(link)
        if href is None:
            return _inline(link.text, link=True)
        text = link.text or self.index[link.target].title
        return f"[{_inline(text, link=True)}]({href})"

    def links(self, links: Iterable[Link]) -> str:
        return ", ".join(text for text in map(self.link, links) if text)

    # -- sections ----------------------------------------------------------

    def body(self, section: Section) -> list[str]:
        """A section's blocks: diagram, paragraphs, items, then symbols."""
        blocks: list[str] = []
        if self.diagrams and section.diagram.strip():
            blocks.append(_fence(section.diagram, "mermaid"))
        for text in section.text:
            blocks.extend(_paragraphs(text))
        if section.items:
            blocks.append(self.items(section))
        if section.symbols:
            blocks.extend(self.symbols(section.symbols))
        return [block for block in blocks if block]

    def facts(self, section: Section) -> list[str]:
        """The facts section as one line, plus any paragraphs it carries."""
        parts: list[str] = []
        for item in section.items:
            text, links = _inline(item.text), self.links(item.links)
            part = f"**{text}:** {links}" if text and links else text or links
            if part:
                parts.append(part)
        blocks = [_block_start(" · ".join(parts))] if parts else []
        for text in section.text:
            blocks.extend(_paragraphs(text))
        return blocks

    def items(self, section: Section) -> str:
        key = section.key
        if key == "components":
            return _table(("File", "Summary"), [
                (self.link(item.links[0]) if item.links else "", _inline(item.text))
                for item in section.items
            ])
        if key == "component-map":
            return _table(("Component", "Responsibility", "Depends on"), [
                (
                    self.link(item.links[0]) if item.links else "",
                    _inline(item.text),
                    self.links(item.links[1:]),
                )
                for item in section.items
            ])
        if key == "dependencies":
            lines = [self.dependency(item) for item in section.items]
        elif key == "entry-points":
            lines = [self.entry(item) for item in section.items]
        else:
            line_ref = key == "known-issues"
            lines = [self.bullet(item, line_ref=line_ref) for item in section.items]
        lines = [_block_start(line) for line in lines if line]
        if section.ordered or key == "data-flow":
            return "\n".join(f"{n}. {line}" for n, line in enumerate(lines, 1))
        return "\n".join(f"- {line}" for line in lines)

    def bullet(self, item: Item, *, line_ref: bool) -> str:
        """`text — links`; with `line_ref`, a positive line leads as `L12:`."""
        text = _inline(item.text)
        if line_ref and item.line > 0:
            text = f"L{item.line}: {text}" if text else f"L{item.line}"
        links = self.links(item.links)
        return f"{text} — {links}" if text and links else text or links

    def dependency(self, item: Item) -> str:
        """`**label:** targets`, where a target-less link names a package."""
        rendered = ", ".join(
            text
            for text in (
                self.link(link) if link.target else _code(link.text)
                for link in item.links
            )
            if text
        )
        text = _inline(item.text)
        return f"**{text}:** {rendered}" if text and rendered else text or rendered

    def entry(self, item: Item) -> str:
        links, text = self.links(item.links), _inline(item.text)
        return f"{links} — {text}" if links and text else links or text

    # -- symbols -----------------------------------------------------------

    def symbols(self, symbols: Sequence[SymbolDoc]) -> list[str]:
        """One block per symbol, then every constant in a single table."""
        blocks: list[str] = []
        for symbol in symbols:
            if symbol.kind != "constant":
                blocks.extend(self.symbol(symbol))
        constants = [symbol for symbol in symbols if symbol.kind == "constant"]
        if constants:
            blocks.append(_table(("Constant", "Definition"), [
                (self.anchor(s) + _code(s.name or s.qualname), self.definition(s))
                for s in constants
            ]))
        return blocks

    def symbol(self, symbol: SymbolDoc) -> list[str]:
        heading = f"### {_code(symbol.name or symbol.qualname)}"
        if symbol.is_async:
            heading += " (async)"
        anchor = self.anchor(symbol)
        blocks = [f"{anchor}\n{heading}" if anchor else heading]
        if symbol.signature.strip():
            blocks.append(_fence(symbol.signature, self.language))
        blocks.extend(_paragraphs(symbol.summary))
        bases = ", ".join(_code(base) for base in symbol.bases if base)
        if bases:
            blocks.append(f"Bases: {bases}")
        decorators = ", ".join(
            _code(d if d.startswith("@") else f"@{d}") for d in symbol.decorators if d
        )
        if decorators:
            blocks.append(f"Decorators: {decorators}")
        blocks.append(self.members(symbol.members))
        return blocks

    def members(self, members: Sequence[SymbolDoc], depth: int = 0) -> str:
        """Members as a bullet list, nested members indented beneath them.

        A member with nothing to show gets no empty bullet; its own members
        take its place.
        """
        lines: list[str] = []
        for member in members:
            code = _code(member.signature or member.name or member.qualname)
            summary = _inline(member.summary)
            shown = f"{code} — {summary}" if code and summary else code or summary
            if shown:
                line = self.anchor(member) + (shown if code else _block_start(shown))
                lines.append(f"{'  ' * depth}- {line}")
            nested = self.members(member.members, depth + 1 if shown else depth)
            if nested:
                lines.append(nested)
        return "\n".join(lines)

    def definition(self, constant: SymbolDoc) -> str:
        parts = (_code(constant.signature), _inline(constant.summary))
        return " — ".join(part for part in parts if part)

    def anchor(self, symbol: SymbolDoc) -> str:
        """The symbol's anchor tag, once per page: ids must stay unique."""
        name = symbol.anchor
        if name in self.anchors:
            return ""
        self.anchors.add(name)
        return f'<a id="{name}"></a>'


# -- blocks ----------------------------------------------------------------


def _front_matter(document: Document, schema: str) -> str:
    """YAML front matter: JSON strings are valid YAML, so no YAML writer needed."""
    meta = document.meta
    confidence = "" if meta.confidence == "exact" else meta.confidence
    fields: tuple[tuple[str, str | int], ...] = (
        ("id", document.id),
        ("kind", str(document.kind)),
        ("title", document.title),
        ("source", meta.source),
        ("source_hash", meta.source_hash),
        ("language", meta.language),
        ("mode", str(meta.mode)),
        ("model", meta.model),
        ("tier", meta.tier),
        ("input_tokens", meta.input_tokens),
        ("output_tokens", meta.output_tokens),
        ("confidence", confidence),
        ("schema", schema),
    )
    lines = ["---"]
    for key, value in fields:
        if isinstance(value, int):
            if value > 0:
                lines.append(f"{key}: {value}")
        elif value:
            lines.append(f"{key}: {json.dumps(value)}")
    lines.append("---")
    return "\n".join(lines)


def _heading(level: int, text: str) -> str:
    """An ATX heading; a trailing `#` run is escaped so it is not dropped."""
    title = _CLOSING.sub(r"\1\\\2", _inline(text))
    return f"{'#' * level} {title}".rstrip()


def _titled(key: str) -> str:
    return key.replace("-", " ").strip().capitalize()


def _paragraphs(text: str) -> list[str]:
    """Each blank-line-separated part of `text` as a one-line paragraph."""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    found = (_block_start(_inline(part)) for part in _PARAGRAPH.split(text))
    return [paragraph for paragraph in found if paragraph]


def _table(header: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    """A GFM table of already-rendered inline cells; "" when every row is empty."""
    body = [row for row in rows if any(row)]
    if not body:
        return ""
    lines = [_row(header), _row(["---"] * len(header))]
    lines.extend(_row(row) for row in body)
    return "\n".join(lines)


def _row(cells: Sequence[str]) -> str:
    padded = (f" {_pipes(cell)} " if cell else " " for cell in cells)
    return "|" + "|".join(padded) + "|"


def _pipes(cell: str) -> str:
    """Escape every `|`, code spans included: GFM splits cells before inlines."""
    return cell.replace("|", "\\|")


def _fence(code: str, info: str = "") -> str:
    """A fenced block, its fence longer than any backtick run inside."""
    body = "\n".join(line.rstrip() for line in code.splitlines()).strip("\n")
    longest = max((len(run) for run in _BACKTICKS.findall(body)), default=0)
    fence = "`" * max(3, longest + 1)
    return f"{fence}{_INFO.sub('', info)}\n{body}\n{fence}"


def _finish(blocks: Iterable[str]) -> bytes:
    """Join blocks into a page: LF, no trailing spaces, single blank lines,
    one final newline. Unencodable characters degrade to `?`, never raise."""
    lines: list[str] = []
    for line in "\n\n".join(blocks).splitlines():
        line = line.rstrip()
        if line or (lines and lines[-1]):
            lines.append(line)
    return ("\n".join(lines).rstrip("\n") + "\n").encode("utf-8", "replace")


# -- inline text -----------------------------------------------------------


def _inline(text: str, *, link: bool = False) -> str:
    """`text` as one line of inline Markdown: syntax escaped, code spans kept.

    `link` also escapes square brackets, for text that becomes link text.
    Stripping, and the `?` that encoding makes of a lone surrogate, come
    first, so escaping judges what lands on the line: a `*` or `<` that looked
    inert beside a space or a surrogate could otherwise open a list or HTML.
    """
    parts: list[str] = []
    for code, chunk in code_spans(_SURROGATE.sub("?", text).strip()):
        if code:
            parts.append(" ".join(chunk.splitlines()))
        else:
            parts.append(_escape(_BREAK.sub(" ", chunk), link=link))
    return "".join(parts)


def _escape(text: str, *, link: bool) -> str:
    """Backslash-escape what would turn plain text into Markdown syntax.

    Emphasis and strikethrough characters are escaped only where they could
    open or close a pair, so `snake_case` and `a * b` stay as written.
    """

    def escaped(match: re.Match[str]) -> str:
        run = match.group()
        start, end = match.span()
        before = text[start - 1] if start else ""
        after = text[end] if end < len(text) else ""
        first = run[0]
        if first in "*~":
            keep = before.isspace() and after.isspace()
        elif first == "_":
            keep = before.isalnum() and after.isalnum()
        elif first == "<":
            tag = (after.isascii() and after.isalpha()) or after in ("/", "!", "?")
            keep = not tag
        elif first == "&":
            keep = _ENTITY.match(text, start) is None
        elif first in "[]":
            keep = not link and not (first == "]" and after in ("(", "[", ":"))
        else:
            keep = False   # backslash, stray backtick
        return run if keep else "".join(f"\\{char}" for char in run)

    return _SPECIAL.sub(escaped, text)


def _block_start(text: str) -> str:
    """Escape a leading heading, quote, list, rule or task marker in `text`.

    Fences need no case here: `_escape` has already escaped a leading `~` or
    stray backtick, and a code span keeps its closing backticks on its line.
    """
    match = _BLOCK.match(text)
    if match is None:
        return text
    if text[0].isdigit():
        return f"{text[: match.end()]}\\{text[match.end() :]}"
    return f"\\{text}"


def _code(text: str) -> str:
    """`text` as one code span, delimited to survive the backticks inside it."""
    text = " ".join(text.splitlines())
    if not text:
        return ""
    longest = max((len(run) for run in _BACKTICKS.findall(text)), default=0)
    ticks = "`" * (longest + 1)
    padded = text[0] == "`" or text[-1] == "`" or (
        text[0] == " " and text[-1] == " " and bool(text.strip())
    )
    pad = " " if padded else ""
    return f"{ticks}{pad}{text}{pad}{ticks}"
