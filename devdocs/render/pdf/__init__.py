_LEAD = {
    DocKind.FILE: "purpose",
    DocKind.MODULE: "purpose",
    DocKind.ARCHITECTURE: "overview",
}
_FACTS = "facts"
_GROUPS = {DocKind.MODULE: "Modules", DocKind.FILE: "Files"}
_FOOTER = "Generated by devdocs; edit the source, not these pages."
_OVERVIEW = "#overview"
_CONTENTS = "#contents"
_OVERVIEW_FILE = "pdf/index.pdf"
_FONT_RESOURCES = {font.resource: font.base for font in FONTS}
_PRODUCER = f"devdocs {__version__} built-in PDF engine"
_PARAGRAPH = re.compile(r"\n[ \t]*\n\s*")
_SPACES = re.compile(r"[^\S\xa0]+")                 # no-break spaces stay
_UNSHOWN = re.compile("[\x00-\x1f\x7f-\x9f\ud800-\udfff]")

Spans = tuple[layout.Span, ...]


class PdfRenderer:
    """Renders a DocSet to PDF: one bound book, or with `split` one file per
    document. `engine` "chrome" or "weasyprint" prints the HTML book with
    that tool instead of the built-in writer."""

    format = "pdf"

    def __init__(
        self, *, split: bool = False, page_size: str = "A4", engine: str = "builtin"
    ) -> None:
        sizes = {name.casefold(): name for name in layout.PAGE_SIZES}
        if page_size.casefold() not in sizes:
            raise ConfigError(
                f"unknown PDF page size {page_size!r}",
                hint="use " + " or ".join(layout.PAGE_SIZES),
            )
        if engine not in external.ENGINES:
            raise ConfigError(
                f"unknown PDF engine {engine!r}",
                hint="use one of: " + ", ".join(external.ENGINES),
            )
        if split and engine != "builtin":
            raise ConfigError(
                f"the {engine} PDF engine prints one book and cannot split it",
                hint="split with the builtin engine, or print a single book",
            )
        self.split = split
        self.page_size = sizes[page_size.casefold()]
        self.engine = engine
        self.warnings: list[str] = []

    def render(self, docset: DocSet) -> dict[str, bytes]:
        """Every PDF, keyed by POSIX path under the out dir. Refills `warnings`
        with each character the built-in fonts could not show, and where."""
        self.warnings.clear()
        if self.engine != "builtin":
            data = external.render(self.engine, docset, page_size=self.page_size)
            return {_book_name(docset.project): data}
        book = _Book(docset, layout.PAGE_SIZES[self.page_size])
        if self.split:
            files = book.split()
        else:
            files = {_book_name(docset.project): book.bound()}
        self.warnings.extend(book.warnings)
        return files


@dataclass(frozen=True)
class _Chapter:
    """A document as the book holds it: blocks plus what binds them in."""

    title: str                          # contents, bookmarks and running head
    heading: str                        # the page's own first heading
    name: str                           # destination at that heading
    blocks: tuple[layout.Block, ...]
    sections: tuple[writer.Bookmark, ...]
    label: str                          # where missing characters are reported
    summary: str = ""
    group: str = ""                     # contents group: "", Modules or Files
    path: str = ""                      # the file it is written to when split


class _Book:
    """Typesets a DocSet's chapters and binds them into PDF files."""

    def __init__(self, docset: DocSet, size: layout.PageSize) -> None:
        self.docset = docset
        self.size = size
        self.project = docset.project or "Documentation"
        self.warnings: list[str] = []

    def bound(self) -> bytes:
        """The whole book: cover, contents, then every chapter."""
        chapters = self.chapters(None)
        flows = [self.typeset(chapter) for chapter in chapters]
        cover = layout.typeset(self.cover(), self.size)
        contents = self.contents(chapters, flows, len(cover.sheets))
        parts: list[tuple[str | None, layout.Flow]] = [
            (None, cover), ("Contents", contents),
            *zip((chapter.title for chapter in chapters), flows, strict=True),
        ]
        outline = [writer.Bookmark("Contents", _CONTENTS)]
        outline += [writer.Bookmark(_plain(c.title), c.name, c.sections)
                    for c in chapters]
        info = self.info(self.project, self.docset.description)
        return self.bind(parts, outline=outline, info=info, here="", placed=None)

    def split(self) -> dict[str, bytes]:
        """One file per chapter; links between them name the sibling file."""
        paths = _split_paths(self.docset.sorted())
        chapters = self.chapters(paths)
        flows = [self.typeset(chapter) for chapter in chapters]
        placed = {
            chapter.path: set(flow.destinations)
            for chapter, flow in zip(chapters, flows, strict=True)
        }
        files: dict[str, bytes] = {}
        for chapter, flow in zip(chapters, flows, strict=True):
            outline = [writer.Bookmark(_plain(chapter.title), chapter.name,
                                       chapter.sections, open=True)]
            info = self.info(chapter.heading, chapter.summary)
            files[chapter.path] = self.bind(
                [(chapter.title, flow)], outline=outline, info=info, here=chapter.path,
                placed=placed,
            )
        return dict(sorted(files.items()))

    # -- chapters ----------------------------------------------------------

    def chapters(self, paths: Mapping[str, str] | None) -> list[_Chapter]:
        """The overview, then every document in reading order."""
        index = {document.id: document for document in self.docset.documents}
        links = _Links(index, paths)
        chapters = [self.overview(links, _OVERVIEW_FILE if paths is not None else "")]
        for document in self.docset.sorted():
            page = _Blocks(links, document.id)
            blocks = page.document(document)
            chapters.append(_Chapter(
                title=document.title,
                heading=document.title,
                name=document.id,
                blocks=tuple(blocks),
                sections=tuple(page.sections),
                label=_plain(document.title),
                summary=document.summary,
                group=_GROUPS.get(document.kind, ""),
                path=paths[document.id] if paths is not None else "",
            ))
        return chapters

    def overview(self, links: _Links, path: str) -> _Chapter:
        """The README's content: description, architecture, modules, files."""
        docset = self.docset
        page = _Blocks(links, _OVERVIEW)
        blocks: list[layout.Block] = [
            layout.Heading(1, _inline(self.project), _OVERVIEW)
        ]
        blocks += page.paragraphs(docset.description)
        architecture = docset.by_kind(DocKind.ARCHITECTURE)
        if architecture:
            document = architecture[0]
            line = page.link(Link("Architecture", document.id))
            blocks.append(layout.Paragraph(_join(
                [line, _inline(document.summary)], " — "
            )))
        modules = docset.by_kind(DocKind.MODULE)
        if modules:
            blocks.append(page.heading("Modules", "modules"))
            blocks += page.table(("Module", "Summary"), [
                (page.link(Link(d.meta.source or "(root)", d.id)), _inline(d.summary))
                for d in modules
            ])
        files = docset.by_kind(DocKind.FILE)
        if files:
            blocks.append(page.heading("Files", "files"))
            blocks += page.table(("File", "Summary"), [
                (page.link(Link(d.meta.source or d.title, d.id)), _inline(d.summary))
                for d in files
            ])
        blocks.append(layout.Paragraph((layout.Span(_FOOTER),), layout.SMALL))
        return _Chapter(
            title="Overview",
            heading=self.project,
            name=_OVERVIEW,
            blocks=tuple(blocks),
            sections=tuple(page.sections),
            label="the overview",
            summary=docset.description,
            path=path,
        )

    def cover(self) -> list[layout.Block]:
        blocks: list[layout.Block] = [
            layout.Space(self.size.height * 0.2),
            layout.Rule(48.0, 3.0, layout.ACCENT),
            layout.Space(18.0),
            layout.Paragraph((layout.Span(self.project),), layout.TITLE),
        ]
        blocks += [
            layout.Paragraph(_inline(part), layout.LEAD)
            for part in _split_paragraphs(self.docset.description)
        ]
        run = self.docset.run
        details = (
            ("Generated by", run.generator if run is not None else ""),
            ("Git commit", run.git_commit[:12] if run is not None else ""),
        )
        shown = [(label, value) for label, value in details if value]
        if shown:
            blocks.append(layout.Space(36.0))
            blocks += [
                layout.Paragraph(
                    (layout.Span(f"{label}: ", BOLD), layout.Span(value)), layout.SMALL
                )
                for label, value in shown
            ]
        return blocks

    def contents(
        self, chapters: Sequence[_Chapter], flows: Sequence[layout.Flow], before: int
    ) -> layout.Flow:
        """The table of contents after `before` pages, numbered right.

        Laid out once to learn its own length, then with the numbers that
        length implies; its numbers have a fixed column, so that settles."""
        numbers: dict[str, str] = {}
        for _ in range(3):
            flow = layout.typeset(self.contents_blocks(chapters, numbers), self.size)
            page = before + len(flow.sheets) + 1
            settled: dict[str, str] = {}
            for chapter, chapter_flow in zip(chapters, flows, strict=True):
                settled[chapter.name] = str(page)
                page += len(chapter_flow.sheets)
            if settled == numbers:
                return flow
            numbers = settled
        raise RuntimeError("the table of contents did not settle")

    @staticmethod
    def contents_blocks(
        chapters: Sequence[_Chapter], numbers: Mapping[str, str]
    ) -> list[layout.Block]:
        blocks: list[layout.Block] = [
            layout.Heading(1, (layout.Span("Contents"),), _CONTENTS)
        ]
        group = ""
        for chapter in chapters:
            if chapter.group != group:
                blocks.append(layout.Entry(chapter.group))
                group = chapter.group
            blocks.append(layout.Entry(
                chapter.title,
                numbers.get(chapter.name, ""),
                layout.Target(chapter.name),
                level=1 if chapter.group else 0,
            ))
        return blocks

    # -- binding -----------------------------------------------------------

    def typeset(self, chapter: _Chapter) -> layout.Flow:
        """`chapter` on pages; what its fonts lack goes to `warnings`."""
        missing: set[str] = set()
        flow = layout.typeset(chapter.blocks, self.size, missing=missing)
        self.warnings += [f"{describe(c)} in {chapter.label}" for c in sorted(missing)]
        return flow

    def bind(
        self,
        parts: Sequence[tuple[str | None, layout.Flow]],
        *,
        outline: Sequence[writer.Bookmark],
        info: Mapping[str, str],
        here: str,
        placed: Mapping[str, Collection[str]] | None,
    ) -> bytes:
        """One PDF file of `parts`, each (running-head title, pages); a part
        without a title has no running head or folio. `placed` holds every
        output file's destinations, for links into them; None for one book."""
        total = sum(len(flow.sheets) for _, flow in parts)
        sheets: list[layout.Sheet] = []
        destinations: dict[str, tuple[int, float]] = {}
        for title, flow in parts:
            offset = len(sheets)
            for name, (index, top) in flow.destinations.items():
                destinations.setdefault(name, (offset + index, top))
            for sheet in flow.sheets:
                if title is not None:
                    layout.decorate(sheet, self.size, left=_plain(self.project),
                                    right=_plain(title),
                                    folio=f"Page {len(sheets) + 1} of {total}")
                sheets.append(sheet)
        names = placed if placed is not None else {here: destinations}
        pages = [
            writer.Page(self.size.width, self.size.height, sheet.content.finish(),
                        tuple(_areas(sheet, here, names)))
            for sheet in sheets
        ]
        return writer.build(pages, fonts=_FONT_RESOURCES, destinations=destinations,
                            outline=outline, info=info)

    @staticmethod
    def info(title: str, subject: str) -> dict[str, str]:
        info = {
            "Title": _plain(title),
            "Subject": _plain(subject),
            "Creator": f"devdocs {__version__}",
            "Producer": _PRODUCER,
        }
        return {key: value for key, value in info.items() if value}


class _Links:
    """Model links as layout targets: the named destination and, in split
    output, the file that holds it."""

    def __init__(
        self, index: Mapping[str, Document], paths: Mapping[str, str] | None
    ) -> None:
        self.index = index
        self.paths = paths

    def target(self, link: Link) -> layout.Target | None:
        document = self.index.get(link.target) if link.target else None
        if document is None:
            return None
        name = f"{document.id}#{link.anchor}" if link.anchor else document.id
        path = self.paths[document.id] if self.paths is not None else ""
        return layout.Target(name, path, fallback=document.id)


class _Blocks:
    """One page's blocks, in the order and shape markdown.py gives the page."""

    def __init__(self, links: _Links, owner: str) -> None:
        self.links = links
        self.owner = owner                  # the page's own destination
        self.names: set[str] = set()
        self.sections: list[writer.Bookmark] = []

    def name(self, fragment: str) -> str:
        """A destination on this page; "" when it is already placed."""
        name = f"{self.owner}#{fragment}"
        if name in self.names:
            return ""
        self.names.add(name)
        return name

    def heading(self, title: str, key: str) -> layout.Heading:
        """A section heading, bookmarked under the page."""
        name = self.name(key)
        if name:
            self.sections.append(writer.Bookmark(_plain(title), name))
        return layout.Heading(2, _inline(title), name)

    # -- inline ------------------------------------------------------------

    def link(self, link: Link) -> Spans:
        target = self.links.target(link)
        if target is None:
            return _inline(link.text)
        text = link.text or self.links.index[link.target].title
        return _inline(text, target=target)

    def joined(self, links: Iterable[Link]) -> Spans:
        return _join([self.link(link) for link in links], ", ")

    @staticmethod
    def labelled(label: str, value: Spans) -> Spans:
        """`label: value` with the label in bold, or whichever is present."""
        text = _inline(label)
        if _visible(text) and _visible(value):
            return (*_inline(f"{label}:", BOLD), layout.Span(" "), *value)
        return text if _visible(text) else value

    def paragraphs(self, text: str) -> list[layout.Block]:
        return [layout.Paragraph(_inline(part)) for part in _split_paragraphs(text)]

    # -- sections ----------------------------------------------------------

    def document(self, document: Document) -> list[layout.Block]:
        """Title, lead section, facts, then the rest in SECTION_ORDER."""
        blocks: list[layout.Block] = [
            layout.Heading(1, _inline(document.title), self.owner)
        ]
        lead = _LEAD.get(document.kind, "purpose")
        for section in document.sections:
            if section.key == lead:
                blocks += self.body(section)
        for section in document.sections:
            if section.key == _FACTS:
                blocks += self.facts(section)
        rank = {key: position for position, key in enumerate(SECTION_ORDER.get(
            document.kind, ()
        ))}
        rest = sorted(
            (s for s in document.sections if s.key not in (lead, _FACTS)),
            key=lambda section: rank.get(section.key, len(rank)),
        )
        for section in rest:
            body = self.body(section)
            if body:
                title = section.title or _titled(section.key)
                blocks.append(self.heading(title, section.key))
                blocks += body
        return blocks

    def body(self, section: Section) -> list[layout.Block]:
        """A section's blocks: diagram, paragraphs, items, then symbols."""
        blocks: list[layout.Block] = []
        if section.diagram.strip():
            blocks.append(_figure(section.diagram))
        for text in section.text:
            blocks += self.paragraphs(text)
        if section.items:
            blocks += self.items(section)
        if section.symbols:
            blocks += self.symbols(section.symbols)
        return blocks

    def facts(self, section: Section) -> list[layout.Block]:
        """The facts as one line, then any paragraphs they carry."""
        parts = [self.labelled(item.text, self.joined(item.links))
                 for item in section.items]
        blocks: list[layout.Block] = []
        if any(_visible(part) for part in parts):
            blocks.append(layout.Paragraph(_join(parts, " · ")))
        for text in section.text:
            blocks += self.paragraphs(text)
        return blocks

    def items(self, section: Section) -> list[layout.Block]:
        key = section.key
        if key == "components":
            return self.table(("File", "Summary"), [
                (self.link(item.links[0]) if item.links else (), _inline(item.text))
                for item in section.items
            ])
        if key == "component-map":
            return self.table(("Component", "Responsibility", "Depends on"), [
                (
                    self.link(item.links[0]) if item.links else (),
                    _inline(item.text),
                    self.joined(item.links[1:]),
                )
                for item in section.items
            ])
        if key == "dependencies":
            lines = [self.dependency(item) for item in section.items]
        elif key == "entry-points":
            lines = [_join([self.joined(item.links), _inline(item.text)], " — ")
                     for item in section.items]
        else:
            line_ref = key == "known-issues"
            lines = [self.bullet(item, line_ref=line_ref) for item in section.items]
        items = tuple(layout.ListItem(line) for line in lines if _visible(line))
        if not items:
            return []
        return [layout.ListBlock(items, ordered=section.ordered or key == "data-flow")]

    def table(
        self, header: tuple[str, ...], rows: Iterable[tuple[Spans, ...]]
    ) -> list[layout.Block]:
        """A table of the rows that show anything; none when no row does."""
        shown = tuple(layout.Row(cells) for cells in rows if any(map(_visible, cells)))
        return [layout.Table(header, shown)] if shown else []

    def bullet(self, item: Item, *, line_ref: bool) -> Spans:
        """`text — links`; with `line_ref`, a positive line leads as `L12:`."""
        text = item.text
        if line_ref and item.line > 0:
            text = f"L{item.line}: {text}" if text.strip() else f"L{item.line}"
        return _join([_inline(text), self.joined(item.links)], " — ")

    def dependency(self, item: Item) -> Spans:
        """`label: targets`, where a link without a target names a package."""
        targets = _join(
            [self.link(link) if link.target else _code(link.text)
             for link in item.links],
            ", ",
        )
        return self.labelled(item.text, targets)

    # -- symbols -----------------------------------------------------------

    def symbols(self, symbols: Sequence[SymbolDoc]) -> list[layout.Block]:
        """One block run per symbol, then every constant in a single table."""
        blocks: list[layout.Block] = []
        for symbol in symbols:
            if symbol.kind != "constant":
                blocks += self.symbol(symbol)
        rows = tuple(
            layout.Row((_code(s.name or s.qualname), self.definition(s)),
                       self.name(s.anchor))
            for s in symbols if s.kind == "constant"
        )
        if rows:
            blocks.append(layout.Table(("Constant", "Definition"), rows))
        return blocks

    def symbol(self, symbol: SymbolDoc) -> list[layout.Block]:
        title = [layout.Span(symbol.name or symbol.qualname, CODE_BOLD)]
        if symbol.is_async:
            title.append(layout.Span(" (async)", BOLD_ITALIC))
        blocks: list[layout.Block] = [
            layout.Heading(3, tuple(title), self.name(symbol.anchor))
        ]
        signature = _code_block(symbol.signature)
        if signature:
            blocks.append(layout.Code(signature))
        blocks += self.paragraphs(symbol.summary)
        bases = _join([_code(base) for base in symbol.bases], ", ")
        if bases:
            blocks.append(layout.Paragraph((layout.Span("Bases: "), *bases)))
        decorators = _join(
            [_code(d if d.startswith("@") else f"@{d}")
             for d in symbol.decorators if d],
            ", ",
        )
        if decorators:
            blocks.append(layout.Paragraph((layout.Span("Decorators: "), *decorators)))
        members = tuple(self.members(symbol.members))
        if members:
            blocks.append(layout.ListBlock(members))
        return blocks

    def members(
        self, members: Sequence[SymbolDoc], depth: int = 0
    ) -> Iterator[layout.ListItem]:
        """Members as list items, nested members indented beneath them; a
        member with nothing to show gives its place to its own members."""
        for member in members:
            code = _code(member.signature or member.name or member.qualname)
            shown = _join([code, _inline(member.summary)], " — ")
            if _visible(shown):
                yield layout.ListItem(shown, depth, self.name(member.anchor))
            yield from self.members(
                member.members, depth + 1 if _visible(shown) else depth
            )

    def definition(self, constant: SymbolDoc) -> Spans:
        return _join([_code(constant.signature), _inline(constant.summary)],
                     " — ")


def _areas(
    sheet: layout.Sheet, here: str, placed: Mapping[str, Collection[str]]
) -> Iterator[writer.LinkArea]:
    """`sheet`'s links as link areas, each to its destination if that was
    placed, else to its fallback; a link to neither is left plain text."""
    for rect, target in sheet.links:
        path = target.file or here
        names = placed.get(path, ())
        name = next((n for n in (target.name, target.fallback) if n and n in names), "")
        if name:
            file = "" if path == here else relpath(path, posixpath.dirname(here))
            yield writer.LinkArea(rect, name, file)


def _figure(source: str) -> layout.Block:
    """A Mermaid diagram drawn, or shown as source when it is not the
    subset `diagram` reads."""
    graph = diagram.parse_mermaid(source)
    if graph is None or not graph.nodes:
        return layout.Code(_code_block(source))
    return layout.figure(graph)


def _inline(
    text: str, font: Font | None = None, target: layout.Target | None = None
) -> Spans:
    """`text` as spans: code spans in Courier, showing what CommonMark shows,
    the rest in `font`."""
    code = CODE_BOLD if font in (BOLD, BOLD_ITALIC) else CODE
    return tuple(
        layout.Span(code_text(chunk), code, target) if is_code
        else layout.Span(chunk, font, target)
        for is_code, chunk in code_spans(text)
    )


def _code(text: str) -> Spans:
    """`text` as one code span on one line."""
    text = " ".join(text.splitlines())
    return (layout.Span(text, CODE),) if text else ()


def _titled(key: str) -> str:
    return key.replace("-", " ").strip().capitalize()


def _visible(spans: Spans) -> bool:
    return any(span.text.strip() for span in spans)


def _join(parts: Iterable[Spans], separator: str) -> Spans:
    """The visible `parts`, with `separator` between them."""
    out: list[layout.Span] = []
    for part in parts:
        if _visible(part):
            if out:
                out.append(layout.Span(separator))
            out.extend(part)
    return tuple(out)


def _split_paragraphs(text: str) -> list[str]:
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return [part.strip() for part in _PARAGRAPH.split(text) if part.strip()]


def _code_block(code: str) -> str:
    """Code as a block shows it: trailing spaces and outer blank lines gone."""
    return "\n".join(line.rstrip() for line in code.splitlines()).strip("\n")


def _split_paths(documents: Sequence[Document]) -> dict[str, str]:
    """Each document's file in split output: `pdf/<path>.pdf`, the root
    module's `pdf/root.pdf`, and a `-2`, `-3` suffix for a name taken, in
    any case or normalization."""
    taken = {folded(_OVERVIEW_FILE)}
    paths: dict[str, str] = {}
    for document in documents:
        root = document.kind is DocKind.MODULE and document.path == Layout.module("")
        stem = "pdf/" + ("root" if root else document.path)
        paths[document.id] = claim(stem, ".pdf", taken)
    return paths


def _book_name(project: str) -> str:
    """The bound book's file: the project's name as a slug."""
    plain = unicodedata.normalize("NFKD", project).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", plain.lower()).strip("-")
    return f"{slug or 'documentation'}.pdf"


def _plain(text: str) -> str:
    """`text` as a page sets a title, for where the PDF names it outside the
    pages (bookmarks, document information, running heads, warnings): runs
    of white space as one space, and "?" for each control character and
    lone surrogate."""
    return _UNSHOWN.sub("?", _SPACES.sub(" ", text).strip(" "))
