"""PDF output: the whole project as one bound book, or one file per document.

The built-in engine needs nothing installed: it lays pages out itself and
writes them with the standard PDF fonts, which every reader has (see
`fonts`, `layout` and `writer`). A bound book opens with a cover (project,
description and, from the run, the generator and git commit) and a table of
contents with page numbers and links, then holds the overview the Markdown
README gives, the architecture, every module and every file, in the order
the overview lists them, each from a new page and with the same sections as
its Markdown page.
Bookmarks list every document with its sections beneath it, and every page
but the cover carries a running head and "Page N of M". The contents are
laid out twice, because their own length moves every page after them; their
numbers sit in a column of fixed width, so the second pass is as long as
the first.

Split output is one PDF per document at `pdf/<document path>.pdf`, plus
`pdf/index.pdf` for the overview, named the way the HTML site names its
pages: the root module's path, `index`, is the overview's, so it is written
to `pdf/root.pdf`, and should two documents still claim one file, the later
in reading order gets `-2`, `-3` and so on. Names that differ only in case
claim one file too, as they do on the file systems macOS and Windows use by
default (a document at path `Index` would otherwise overwrite the
overview there), and so do names that differ only in Unicode normalization,
as they do on macOS. A link to another document opens
that sibling file at the named destination, with a GoToR action; a reader
that does not follow links between files shows the link as plain text, and
nothing else is lost.

Named destinations are the same in both forms, so a link into another file
needs only that file's path: a document's is its id (`file:shop/cart.py`), a
section's and a symbol's append `#` and the section key or the symbol anchor
(`file:shop/cart.py#sym-Cart-add`), and the overview and the contents are
`#overview` and `#contents`. A link to a symbol the target page shows
without an anchor opens the page instead.

The standard fonts cover WinAnsi, roughly Latin-1. A character outside it
prints as "?" and is listed in `PdfRenderer.warnings` by code point, name and
document, never dropped silently. Bookmarks and the document information
can hold any character, but show a title the way its page does: on one
line, with "?" for a control character. The `chrome` and `weasyprint`
engines print the HTML book instead, with all of Unicode; see `external`.

Output is deterministic, and carries no date: like the HTML pages, the
cover names the run's generator and git commit but not its time, which
changes on every run, so regenerating an unchanged project rewrites no PDF.
"""

