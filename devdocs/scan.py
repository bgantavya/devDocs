"""Walk a project and decide what each file is.

Replaces v3's `chdir`-driven recursion, which corrupted every output path after
one unreadable folder and made concurrency impossible. Paths here are absolute
plus a POSIX relative key; the process working directory is never changed.

What the walk leaves out is recorded in `ScanResult.skipped`, with a reason:

- Ignored: the repository's own rules, applied as git applies them (see
  devdocs.ignore), plus DEFAULT_IGNORES and `exclude`. An ignored directory is
  never entered, unless an `include` path lies beneath it.
- Symlinks: by default never followed, files and directories alike, so nothing
  outside the tree is ever read. With `follow_symlinks` they are followed, but
  a link resolving outside the root is still skipped, and each real directory
  is walked once, under its own path when it has one, which also ends loops.
- Unreadable files and directories, empty and oversized files, and files of
  no recognised kind.

Classification is deterministic and cheap: extension gives the language, path
shape gives the role (source, test, generated, vendored, config, docs), and a
generated-code marker in a file's leading comment block marks it generated.
Nothing here calls a model — the planner later scores these facts to decide
what is worth spending tokens on.
"""

from __future__ import annotations

import os
import re
import stat
from collections.abc import Iterator
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path, PurePosixPath

from devdocs.ignore import GitignoreMatcher

__all__ = ["LANGUAGES", "Role", "ScanResult", "Scanner", "SourceFile"]

# Extension to language. Drives parser selection and syntax highlighting.
LANGUAGES: dict[str, str] = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".jsx": "javascript",
    ".ts": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".tsx": "typescript",
    ".go": "go", ".rs": "rust", ".java": "java", ".kt": "kotlin",
    ".rb": "ruby", ".php": "php", ".cs": "csharp", ".swift": "swift",
    ".c": "c", ".h": "c", ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp",
    ".sh": "shell", ".bash": "shell", ".zsh": "shell",
    ".sql": "sql", ".scala": "scala", ".ex": "elixir", ".exs": "elixir",
    ".lua": "lua", ".dart": "dart", ".vue": "vue", ".svelte": "svelte",
}

_CONFIG_SUFFIXES = {".toml", ".ini", ".cfg", ".yaml", ".yml", ".json", ".env"}
_DOC_SUFFIXES = {".md", ".rst", ".txt", ".adoc"}

# Noise in every project, applied on top of the repository's own rules, which
# cannot re-include it. Caches and tool state at any depth; build output and
# vendored trees only at the root, so a source package named build/ survives.
DEFAULT_IGNORES: tuple[str, ...] = (
    ".git", ".hg/", ".svn/", "node_modules/", "__pycache__/", ".venv/", "venv/",
    ".tox/", ".nox/", ".next/", ".turbo/", ".expo/", ".idea/", ".vscode/",
    ".mypy_cache/", ".ruff_cache/", ".pytest_cache/", "htmlcov/",
    "*.egg-info/", ".devdocs/",
    "/build/", "/dist/", "/target/", "/out/", "/vendor/", "/third_party/",
)

# What in a path marks tests and vendored code.
_TEST_DIRS = {"test", "tests", "__tests__", "spec", "specs", "testing"}
_TEST_PREFIXES = ("test_", "spec_")   # the word, so not testament.py
_TEST_SUFFIXES = ("_test", "_tests", ".test", ".spec")
_PY_TEST_FILES = {"conftest.py", "test.py", "tests.py"}   # not testing.py: often public
_PY_TEST_PREFIX = "tests_"
_VENDOR_DIRS = {"vendor", "third_party", "thirdparty", "external", "node_modules"}

# Generated code: by name, and by the markers generators put in the header.
_GENERATED_SUFFIXES = (
    ".min.js", ".min.css", "_pb2.py", "_pb2.pyi", "_pb2_grpc.py", ".pb.go",
    ".pb.h", ".pb.cc", ".g.dart", ".freezed.dart",
)
_GO_GENERATED = re.compile(r"// Code generated .* DO NOT EDIT\.")
_AT_GENERATED = re.compile(r"(?<![\w@])@generated\b")
_AUTO_GENERATED = re.compile(
    r"\bauto[- ]?generated\b|\bautomatically generated\b"
    r"|\bgenerated by the protocol buffer compiler\b"
)
_DO_NOT_EDIT = re.compile(r"\bdo not (?:edit|modify)\b")
_HEAD_BYTES = 2048


class Role(StrEnum):
    """What a file is for. Drives significance scoring and prompt choice."""

    SOURCE = "source"
    TEST = "test"
    CONFIG = "config"
    DOCS = "docs"
    GENERATED = "generated"
    VENDORED = "vendored"
    DATA = "data"


@dataclass(frozen=True)
class SourceFile:
    """One file worth looking at, with everything classification determined."""

    path: Path
    relpath: str
    language: str
    role: Role
    size: int
    lines: int = 0

    @property
    def is_documentable(self) -> bool:
        """True when this file could carry prose docs.

        Vendored and generated files never do: nobody maintains them, and
        documenting them is the clearest way to waste tokens.
        """
        return self.role in (Role.SOURCE, Role.CONFIG) and self.language != ""

    @property
    def stem(self) -> str:
        return self.path.stem


@dataclass
class ScanResult:
    """Everything a scan found, plus why it skipped the rest."""

    files: list[SourceFile] = field(default_factory=list)
    skipped: dict[str, str] = field(default_factory=dict)
    root: Path = Path(".")

    def by_role(self, role: Role) -> list[SourceFile]:
        return [f for f in self.files if f.role is role]

    def by_language(self) -> dict[str, list[SourceFile]]:
        grouped: dict[str, list[SourceFile]] = {}
        for item in self.files:
            grouped.setdefault(item.language, []).append(item)
        return grouped

    @property
    def documentable(self) -> list[SourceFile]:
        return [f for f in self.files if f.is_documentable]

    def __len__(self) -> int:
        return len(self.files)


class Scanner:
    """Walks a tree and yields classified files.

    Uses os.walk with in-place pruning of `dirnames`, so an ignored directory is
    never descended into. `ignore` replaces the repository's rules and the
    defaults; `exclude` patterns apply either way. `max_bytes` skips files too
    large to be worth reading; the default is generous because the planner,
    not the scanner, decides cost.
    """

    def __init__(
        self,
        root: Path | str = ".",
        *,
        ignore: GitignoreMatcher | None = None,
        include: tuple[str, ...] = (),
        exclude: tuple[str, ...] = (),
        max_bytes: int = 1_000_000,
        follow_symlinks: bool = False,
    ) -> None:
        try:
            self.root = Path(root).resolve()
        except (OSError, RuntimeError):
            self.root = Path(os.path.abspath(root))
        self.max_bytes = max_bytes
        self.follow_symlinks = follow_symlinks
        self.include = tuple(key for key in map(_include_key, include) if key)
        if ignore is None:
            ignore, defaults = GitignoreMatcher.from_root(self.root), DEFAULT_IGNORES
        else:
            defaults = ()
        self.ignore = ignore
        self._excludes = GitignoreMatcher.from_lines(
            [*defaults, *exclude], ignore_case=self.ignore.ignore_case
        )

    def scan(self) -> ScanResult:
        result = ScanResult(root=self.root)
        for path, relpath in self._walk(result.skipped):
            item = self._classify(path, relpath, result.skipped)
            if item is not None:
                result.files.append(item)
        result.files.sort(key=lambda f: f.relpath)
        return result

    def _forced(self, relpath: str) -> bool:
        """True when --include names this path, a directory above it, or a segment.

        A trailing match counts too, so an extension forces every such file.
        """
        if not self.include:
            return False
        lowered = relpath.lower()
        segments = lowered.split("/")
        return any(
            item in segments or lowered.endswith(item) or lowered.startswith(f"{item}/")
            for item in self.include
        )

    def _wanted(self, relpath: str, *, is_dir: bool) -> bool:
        """False when ignore rules leave this path out and --include does not.

        A directory on the way to an --include path is entered regardless;
        only what that path names is then taken from it.
        """
        if self._forced(relpath):
            return True
        prefix = f"{relpath.lower()}/"
        if is_dir and any(item.startswith(prefix) for item in self.include):
            return True
        # On POSIX a backslash is part of a name, not a separator.
        key = PurePosixPath(relpath) if "\\" in relpath else relpath
        return not (
            self._excludes.ignored(key, is_dir=is_dir)
            or self.ignore.ignored(key, is_dir=is_dir)
        )

    def _walk(self, skipped: dict[str, str]) -> Iterator[tuple[Path, str]]:
        """Yield every file the ignore rules keep, in a stable order.

        Directory links found along the way are walked afterwards as tops of
        their own, so a real path always claims a directory before a link does.
        """
        tops = [self.root]
        seen: set[tuple[int, int]] = set()

        def unreadable(err: OSError) -> None:
            rel = self._relative(err.filename or self.root)
            skipped[f"{rel}/" if rel else "./"] = _reason(err)

        while tops:
            top = tops.pop(0)
            if self.follow_symlinks and not _claim(top, seen):
                skipped[f"{self._relative(top)}/"] = "symlink loop"
                continue
            for dirpath, dirnames, filenames in os.walk(top, onerror=unreadable):
                here = Path(dirpath)
                base = self._relative(here)

                keep: list[str] = []
                for name in sorted(dirnames):
                    rel = f"{base}/{name}" if base else name
                    path = here / name
                    if not self._wanted(rel, is_dir=True):
                        skipped[f"{rel}/"] = "ignored"
                    elif os.path.islink(path):
                        reason = self._link(path)
                        if reason:
                            skipped[f"{rel}/"] = reason
                        else:
                            tops.append(path)
                    elif self.follow_symlinks and not _claim(path, seen):
                        skipped[f"{rel}/"] = "symlink loop"
                    else:
                        keep.append(name)
                dirnames[:] = keep

                for name in sorted(filenames):
                    rel = f"{base}/{name}" if base else name
                    if self._wanted(rel, is_dir=False):
                        yield here / name, rel
                    else:
                        skipped[rel] = "ignored"

    def _link(self, path: Path) -> str:
        """Why a symlink is not followed, or "" when it may be."""
        if not self.follow_symlinks:
            return "symlink"
        real = os.path.realpath(path)
        root = str(self.root)
        if real != root and not real.startswith(root.rstrip(os.sep) + os.sep):
            return "symlink outside root"
        return ""

    def _relative(self, path: str | Path) -> str:
        """The POSIX key of a path under the root; "" for the root itself."""
        rel = os.path.relpath(path, self.root)
        return "" if rel == "." else rel.replace(os.sep, "/")

    def _classify(
        self, path: Path, relpath: str, skipped: dict[str, str]
    ) -> SourceFile | None:
        try:
            info = path.lstat()
            if stat.S_ISLNK(info.st_mode):
                reason = self._link(path)
                if reason:
                    skipped[relpath] = reason
                    return None
                info = path.stat()
        except OSError as err:
            skipped[relpath] = _reason(err)
            return None

        if not stat.S_ISREG(info.st_mode):
            skipped[relpath] = "not a regular file"
            return None
        if info.st_size == 0:
            skipped[relpath] = "empty"
            return None
        if info.st_size > self.max_bytes and not self._forced(relpath):
            skipped[relpath] = f"too large ({info.st_size:,} bytes)"
            return None

        suffix = path.suffix.lower()
        language = LANGUAGES.get(suffix, "")
        role = _role(relpath, language, suffix)
        if role is Role.DATA and not self._forced(relpath):
            skipped[relpath] = "not a recognised source or config file"
            return None

        try:
            head, lines = _read(path)
        except OSError as err:
            skipped[relpath] = _reason(err)
            return None
        if role is Role.SOURCE and _generated_header(head):
            role = Role.GENERATED

        return SourceFile(
            path=path,
            relpath=relpath,
            language=language,
            role=role,
            size=info.st_size,
            lines=lines,
        )


def _include_key(item: str) -> str:
    """An --include item as `_forced` compares it: lowercase POSIX, no edge slashes."""
    text = item.strip().replace("\\", "/").lower()
    while text.startswith("./"):
        text = text[2:]
    return text.strip("/")


def _reason(err: OSError) -> str:
    return f"unreadable: {err.strerror or err}"


def _claim(path: Path, seen: set[tuple[int, int]]) -> bool:
    """Record a directory's identity; False when it was walked already."""
    try:
        info = os.stat(path)
    except OSError:
        return True   # os.walk reports it as unreadable
    identity = (info.st_dev, info.st_ino)
    if identity in seen:
        return False
    seen.add(identity)
    return True


def _read(path: Path) -> tuple[bytes, int]:
    """Read a file once: its head, for header sniffing, and its line count."""
    with path.open("rb") as handle:
        head = handle.read(_HEAD_BYTES)
        lines = head.count(b"\n")
        last = head[-1:]
        while chunk := handle.read(1 << 20):
            lines += chunk.count(b"\n")
            last = chunk[-1:]
    return head, lines + (1 if last and last != b"\n" else 0)


def _role(relpath: str, language: str, suffix: str) -> Role:
    """Role from the path alone; a generated header can still demote SOURCE."""
    lowered = relpath.lower()
    *parents, name = lowered.split("/")
    segments = set(parents)

    if segments & _VENDOR_DIRS:
        return Role.VENDORED
    if (
        segments & _TEST_DIRS
        or name in _PY_TEST_FILES
        or name.startswith(_TEST_PREFIXES)
        or (suffix == ".py" and name.startswith(_PY_TEST_PREFIX))
        or any(name.endswith(f"{marker}{suffix}") for marker in _TEST_SUFFIXES)
    ):
        return Role.TEST
    if language and (
        name.endswith(_GENERATED_SUFFIXES)
        or ".generated." in name
        or (language == "python" and _is_migration(segments, lowered))
    ):
        return Role.GENERATED
    if language:
        return Role.SOURCE
    if suffix in _CONFIG_SUFFIXES:
        return Role.CONFIG
    if suffix in _DOC_SUFFIXES:
        return Role.DOCS
    return Role.DATA


def _is_migration(segments: set[str], lowered: str) -> bool:
    """Django and Alembic migrations: written by `makemigrations`/`revision`."""
    return "migrations" in segments or "/alembic/versions/" in f"/{lowered}"


def _generated_header(head: bytes) -> bool:
    """True when the file's leading comment block carries a generated marker.

    Only the header counts, so a test or comment mentioning a marker further
    down cannot flip a hand-written file. The conventions: Go's `// Code
    generated ... DO NOT EDIT.` line, `@generated`, and an auto-generated
    notice paired with "do not edit".
    """
    block = _comment_block(head.decode("utf-8", errors="replace"))
    if any(_GO_GENERATED.fullmatch(line) for line in block):
        return True
    text = "\n".join(block)
    if _AT_GENERATED.search(text):
        return True
    lowered = text.lower()
    return bool(_AUTO_GENERATED.search(lowered) and _DO_NOT_EDIT.search(lowered))


def _comment_block(text: str) -> list[str]:
    """The comment lines that open a file, up to its first line of code."""
    block: list[str] = []
    closer = ""
    for raw in text.removeprefix("\ufeff").splitlines():
        line = raw.strip()
        if closer:
            block.append(line)
            if closer in line:
                closer = ""
        elif not line or line.startswith("<?php"):
            continue
        elif line.startswith(("//", "#", "--", ";")):
            block.append(line)
        elif line.startswith(("/*", "<!--")):
            block.append(line)
            opener, closer = ("/*", "*/") if line.startswith("/*") else ("<!--", "-->")
            if line.find(closer, len(opener)) >= 0:
                closer = ""
        else:
            break
    return block
