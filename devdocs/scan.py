"""Walk a project and decide what each file is.

Replaces v3's `chdir`-driven recursion, which corrupted every output path after
one unreadable folder and made concurrency impossible. Paths here are absolute
plus a POSIX relative key; the process working directory is never changed.

Classification is deterministic and cheap: extension gives the language, path
shape gives the role (source, test, generated, vendored, config, docs). Nothing
here calls a model — the planner later scores these facts to decide what is
worth spending tokens on.
"""

from __future__ import annotations

import os
from collections.abc import Iterator
from dataclasses import dataclass, field
from enum import StrEnum
from pathlib import Path

from devdocs.ignore import GitignoreMatcher

__all__ = ["LANGUAGES", "Role", "ScanResult", "Scanner", "SourceFile"]

# Extension to language. Drives parser selection and syntax highlighting.
LANGUAGES: dict[str, str] = {
    ".py": "python", ".pyi": "python",
    ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript",
    ".jsx": "javascript",
    ".ts": "typescript", ".mts": "typescript", ".cts": "typescript",
    ".tsx": "typescript",
    ".go": "go", ".rs": "rust", ".java": "java", ".kt": "kotlin",
    ".rb": "ruby", ".php": "php", ".cs": "csharp", ".swift": "swift",
    ".c": "c", ".h": "c", ".cpp": "cpp", ".cc": "cpp", ".hpp": "cpp",
    ".sh": "shell", ".bash": "shell", ".zsh": "shell",
    ".sql": "sql", ".scala": "scala", ".ex": "elixir", ".exs": "elixir",
    ".lua": "lua", ".dart": "dart", ".vue": "vue", ".svelte": "svelte",
}

_CONFIG_SUFFIXES = {".toml", ".ini", ".cfg", ".yaml", ".yml", ".json", ".env"}
_DOC_SUFFIXES = {".md", ".rst", ".txt", ".adoc"}

# Directory names that are noise in every project, used when a repo has no
# .gitignore of its own. Whole segments, never substrings.
DEFAULT_IGNORES: tuple[str, ...] = (
    ".git/", "node_modules/", "__pycache__/", ".venv/", "venv/",
    "dist/", "build/", "target/", "vendor/", "third_party/",
    ".next/", ".turbo/", ".expo/", ".idea/", ".vscode/", ".tox/",
    ".mypy_cache/", ".ruff_cache/", ".pytest_cache/", "htmlcov/",
    "*.egg-info/", ".devdocs/",
)

# Path segments that mark tests and vendored code.
_TEST_DIRS = {"test", "tests", "__tests__", "spec", "specs", "testing"}
_VENDOR_DIRS = {"vendor", "third_party", "thirdparty", "external", "node_modules"}

# Generated-file markers, checked against the first 2 KiB.
_GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "do not modify",
    "auto-generated",
    "autogenerated",
    "code generated by",
)


class Role(StrEnum):
    """What a file is for. Drives significance scoring and prompt choice."""

    SOURCE = "source"
    TEST = "test"
    CONFIG = "config"
    DOCS = "docs"
    GENERATED = "generated"
    VENDORED = "vendored"
    DATA = "data"


@dataclass(frozen=True)
class SourceFile:
    """One file worth looking at, with everything classification determined."""

    path: Path
    relpath: str
    language: str
    role: Role
    size: int
    lines: int = 0

    @property
    def is_documentable(self) -> bool:
        """True when this file could carry prose docs.

        Vendored and generated files never do: nobody maintains them, and
        documenting them is the clearest way to waste tokens.
        """
        return self.role in (Role.SOURCE, Role.CONFIG) and self.language != ""

    @property
    def stem(self) -> str:
        return self.path.stem


@dataclass
class ScanResult:
    """Everything a scan found, plus why it skipped the rest."""

    files: list[SourceFile] = field(default_factory=list)
    skipped: dict[str, str] = field(default_factory=dict)
    root: Path = Path(".")

    def by_role(self, role: Role) -> list[SourceFile]:
        return [f for f in self.files if f.role is role]

    def by_language(self) -> dict[str, list[SourceFile]]:
        grouped: dict[str, list[SourceFile]] = {}
        for item in self.files:
            grouped.setdefault(item.language, []).append(item)
        return grouped

    @property
    def documentable(self) -> list[SourceFile]:
        return [f for f in self.files if f.is_documentable]

    def __len__(self) -> int:
        return len(self.files)


class Scanner:
    """Walks a tree and yields classified files.

    Uses os.walk with in-place pruning of `dirnames`, so an ignored directory is
    never descended into. `max_bytes` skips files too large to be worth reading;
    the default is generous because the planner, not the scanner, decides cost.
    """

    def __init__(
        self,
        root: Path | str = ".",
        *,
        ignore: GitignoreMatcher | None = None,
        include: tuple[str, ...] = (),
        exclude: tuple[str, ...] = (),
        max_bytes: int = 1_000_000,
        follow_symlinks: bool = False,
    ) -> None:
        self.root = Path(root).resolve()
        self.max_bytes = max_bytes
        self.follow_symlinks = follow_symlinks
        self.include = tuple(i.lower() for i in include)
        self.ignore = ignore or GitignoreMatcher.from_root(
            self.root, extra=[*DEFAULT_IGNORES, *exclude]
        )

    def scan(self) -> ScanResult:
        result = ScanResult(root=self.root)
        for path, relpath in self._walk(result.skipped):
            item = self._classify(path, relpath, result.skipped)
            if item is not None:
                result.files.append(item)
        result.files.sort(key=lambda f: f.relpath)
        return result

    def _forced(self, relpath: str) -> bool:
        """True when --include names this path or one of its segments."""
        if not self.include:
            return False
        lowered = relpath.lower()
        segments = set(lowered.split("/"))
        return any(
            item in segments or item == lowered or lowered.endswith(item)
            for item in self.include
        )

    def _walk(self, skipped: dict[str, str]) -> Iterator[tuple[Path, str]]:
        for dirpath, dirnames, filenames in os.walk(
            self.root, followlinks=self.follow_symlinks, onerror=None
        ):
            here = Path(dirpath)

            keep: list[str] = []
            for name in dirnames:
                rel = (here / name).relative_to(self.root).as_posix()
                if self._forced(rel):
                    keep.append(name)
                elif self.ignore.ignored(rel, is_dir=True):
                    skipped[rel + "/"] = "ignored"
                else:
                    keep.append(name)
            dirnames[:] = sorted(keep)

            for name in sorted(filenames):
                path = here / name
                rel = path.relative_to(self.root).as_posix()
                if not self._forced(rel) and self.ignore.ignored(rel):
                    skipped[rel] = "ignored"
                    continue
                yield path, rel

    def _classify(
        self, path: Path, relpath: str, skipped: dict[str, str]
    ) -> SourceFile | None:
        try:
            stat = path.stat()
        except OSError as err:
            skipped[relpath] = f"unreadable: {err.strerror}"
            return None

        if not path.is_file():
            return None
        if stat.st_size == 0:
            skipped[relpath] = "empty"
            return None
        if stat.st_size > self.max_bytes and not self._forced(relpath):
            skipped[relpath] = f"too large ({stat.st_size:,} bytes)"
            return None

        suffix = path.suffix.lower()
        language = LANGUAGES.get(suffix, "")
        role = self._role(path, relpath, language, suffix)

        if role is Role.DATA and not self._forced(relpath):
            skipped[relpath] = "not a recognised source or config file"
            return None

        return SourceFile(
            path=path,
            relpath=relpath,
            language=language,
            role=role,
            size=stat.st_size,
            lines=self._count_lines(path),
        )

    def _role(self, path: Path, relpath: str, language: str, suffix: str) -> Role:
        segments = {part.lower() for part in Path(relpath).parts[:-1]}
        name = path.name.lower()

        if segments & _VENDOR_DIRS:
            return Role.VENDORED
        if language and self._looks_generated(path, name):
            return Role.GENERATED
        if segments & _TEST_DIRS or name.startswith(("test_", "spec_")):
            return Role.TEST
        test_markers = ("_test", ".test", ".spec")
        if any(name.endswith(f"{marker}{suffix}") for marker in test_markers):
            return Role.TEST
        if language:
            return Role.SOURCE
        if suffix in _CONFIG_SUFFIXES:
            return Role.CONFIG
        if suffix in _DOC_SUFFIXES:
            return Role.DOCS
        return Role.DATA

    @staticmethod
    def _looks_generated(path: Path, name: str) -> bool:
        """Detect generated code by filename, then by header marker.

        Header sniffing reads 2 KiB, which is cheap next to the cost of
        documenting a 40k-line protobuf stub nobody reads.
        """
        if name.endswith((".min.js", ".min.css", "_pb2.py", "_pb2_grpc.py", ".g.dart")):
            return True
        if ".generated." in name or name.endswith(".pb.go"):
            return True
        try:
            with path.open("r", encoding="utf-8", errors="ignore") as handle:
                head = handle.read(2048).lower()
        except OSError:
            return False
        return any(marker in head for marker in _GENERATED_MARKERS)

    @staticmethod
    def _count_lines(path: Path) -> int:
        try:
            with path.open("rb") as handle:
                return sum(1 for _ in handle)
        except OSError:
            return 0
